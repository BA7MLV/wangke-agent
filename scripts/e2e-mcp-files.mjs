import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { chromium } from 'playwright';
import { createServer } from 'vite';

const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'wangke-mcp-files-ui-'));
const reservation = net.createServer();
await new Promise(resolve => reservation.listen(0, '127.0.0.1', resolve));
const port = reservation.address().port;
await new Promise(resolve => reservation.close(resolve));
const origin = `http://127.0.0.1:${port}`;
Object.assign(process.env, { NODE_ENV: 'test', PUBLIC_ORIGIN: origin, DATA_DIR: directory, FILES_DIR: path.join(directory, 'files'), BOOTSTRAP_SECRET_FILE: path.join(directory, 'config/bootstrap-secret'), CLOUD_WORKER_DISABLED: '1' });
const { buildServer } = await import('../apps/api/src/server.ts');
const api = buildServer({ dbPath: path.join(directory, 'db.sqlite'), fetch: async () => { throw new Error('no model calls expected'); } });
const output = process.env.SCREENSHOT_DIR ?? path.join(directory, 'screenshots');
fs.mkdirSync(output, { recursive: true });
let vite, browser, page;
const errors = [];
try {
  const backend = await api.listen({ host: '127.0.0.1', port: 0 });
  process.env.WANGKE_API_PROXY = backend;
  vite = await createServer({ root: new URL('../apps/web', import.meta.url).pathname, cacheDir: path.join(directory, 'vite-cache'), server: { host: '127.0.0.1', port, strictPort: true } });
  await vite.listen();
  console.log('MCP UI fixture: servers ready');
  browser = await chromium.launch({ channel: 'chrome', headless: true, timeout: 30000 });
  const context = await browser.newContext({ locale: 'zh-CN', serviceWorkers: 'block' });
  context.setDefaultTimeout(30000);
  context.setDefaultNavigationTimeout(90000);
  console.log('MCP UI fixture: browser ready');
  await context.route('https://models.dev/**', route => route.fulfill({ json: {} }));
  const post = async (url, data, headers = {}) => {
    const response = await context.request.post(`${origin}/api/v1${url}`, { headers: { origin, ...headers }, data });
    assert.equal(response.ok(), true, `${url}: ${response.status()} ${await response.text()}`);
    return response;
  };
  await post('/bootstrap/initialize', { adminPassword: 'mcp-files-ui-password' }, { 'X-Bootstrap-Secret': fs.readFileSync(process.env.BOOTSTRAP_SECRET_FILE, 'utf8').trim() });
  await post('/auth/password/login', { password: 'mcp-files-ui-password' });
  const config = await (await context.request.get(`${origin}/api/v1/cloud/config`)).json();
  assert.equal((await context.request.put(`${origin}/api/v1/cloud/config`, { headers: { origin }, data: { ...config, providers: [{ id: 'offline', name: 'Offline', baseUrl: 'https://offline.invalid/v1', protocol: 'openai-chat', apiKey: 'test-only', catalogId: '', serves: ['chat'] }], llmModel: { providerId: 'offline', model: 'test' } } })).ok(), true);
  await post('/cloud/records', { mutations: [{ id: 'language', table: 'preferences', key: 'uiLanguage', before: null, after: { id: 'uiLanguage', value: 'zh-CN' } }] });
  const server = await (await post('/cloud/mcp', { name: 'MCP fixture', url: 'https://example.invalid/mcp', transport: 'streamable-http', enabled: false, auth: 'bearer', token: 'not-in-json', timeoutMs: 30000, disabledTools: [] })).json();
  const file = async () => (await context.request.get(`${origin}/api/v1/system/file?path=/system/mcp.json`)).json();
  console.log('MCP UI fixture: authenticated and seeded');
  page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(`${origin}/#/library`, { waitUntil: 'domcontentloaded' });
    const open = item => width < 600 ? item.click() : item.dblclick();
    await page.getByTestId('system-folder').waitFor({ timeout: 60000 });
    await open(page.getByTestId('system-folder'));
    const resource = page.getByTestId('mcp-config-file');
    await resource.waitFor({ timeout: 30000 });
    assert.match(await resource.innerText(), /mcp\.json/);
    await open(resource);
    const reader = page.getByTestId('mcp-config-reader');
    await reader.waitFor();
    const editor = page.getByTestId('mcp-json-editor');
    await editor.waitFor();
    assert.equal(await reader.getByTestId('mcp-settings').count(), 0, 'resources only expose raw JSON, not visual settings');
    assert.equal(await reader.getByRole('button', { name: '可视化', exact: true }).count(), 0);
    assert.equal(await reader.getByRole('button', { name: 'JSON 编辑', exact: true }).count(), 0, 'JSON opens directly without a view switch');
    const editorReady = () => page.waitForFunction(() => document.querySelector('[data-testid="mcp-json-editor"]')?.disabled === false);
    const original = await editor.inputValue();
    assert.ok(!original.includes('not-in-json'));
    const name = `JSON 编辑 ${width}`;
    const updated = JSON.parse(original); updated.servers[0].name = name;
    await editor.fill(JSON.stringify(updated, null, 2));
    const [saved] = await Promise.all([
      page.waitForResponse(response => response.url().endsWith('/api/v1/system/file') && response.request().method() === 'POST'),
      page.getByTestId('mcp-json-save').click(),
    ]);
    assert.equal(saved.ok(), true, await saved.text());
    await editorReady();
    assert.equal(JSON.parse((await file()).content).servers[0].name, name);
    await editor.fill('{ invalid JSON');
    await page.getByTestId('mcp-json-save').click();
    await page.getByTestId('mcp-json-error').waitFor();
    assert.equal(await editor.inputValue(), '{ invalid JSON');
    assert.equal(JSON.parse((await file()).content).servers[0].name, name);
    await reader.getByRole('button', { name: '放弃草稿并重载', exact: true }).click();
    await editorReady();
    await editor.fill((await editor.inputValue()).replace(name, `未保存草稿 ${width}`));
    const remoteName = `其他页面更新 ${width}`;
    const { revision: _revision, ...input } = server;
    const response = await context.request.put(`${origin}/api/v1/cloud/mcp/${server.id}`, { headers: { origin }, data: { ...input, name: remoteName } });
    assert.equal(response.ok(), true);
    await reader.getByText('文件已在其他页面或 Bot 中更新。草稿已保留，请重载最新版本后再修改。', { exact: true }).waitFor({ timeout: 15000 });
    await page.getByTestId('mcp-json-save').click();
    await page.getByTestId('mcp-json-error').waitFor();
    assert.match(await editor.inputValue(), new RegExp(`未保存草稿 ${width}`));
    assert.equal(JSON.parse((await file()).content).servers[0].name, remoteName);
    await reader.getByRole('button', { name: '放弃草稿并重载', exact: true }).click();
    await editorReady();
    assert.equal(JSON.parse(await editor.inputValue()).servers[0].name, remoteName);
    await page.goto(`${origin}/#/settings/skills`);
    await page.getByRole('button', { name: 'MCP', exact: true }).click();
    const visual = page.getByTestId('mcp-settings');
    await visual.getByRole('heading', { name: remoteName, exact: true }).waitFor();
    await visual.getByRole('button', { name: '编辑服务器', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: '编辑服务器', exact: true });
    await dialog.getByLabel('名称', { exact: true }).fill(`可视化编辑 ${width}`);
    const concurrentVisualName = `表单并发更新 ${width}`;
    const concurrent = await context.request.put(`${origin}/api/v1/cloud/mcp/${server.id}`, { headers: { origin }, data: { ...input, name: concurrentVisualName } });
    assert.equal(concurrent.ok(), true);
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await dialog.getByRole('alert').waitFor();
    assert.equal(await dialog.getByLabel('名称', { exact: true }).inputValue(), `可视化编辑 ${width}`, 'stale visual forms retain their draft');
    assert.equal(JSON.parse((await file()).content).servers[0].name, concurrentVisualName);
    await dialog.getByRole('button', { name: '取消', exact: true }).click();
    await visual.getByRole('heading', { name: concurrentVisualName, exact: true }).waitFor();
    await visual.getByRole('button', { name: '编辑服务器', exact: true }).click();
    await dialog.getByLabel('名称', { exact: true }).fill(`可视化编辑 ${width}`);
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    assert.equal(JSON.parse((await file()).content).servers[0].name, `可视化编辑 ${width}`);
    await visual.getByRole('heading', { name: `可视化编辑 ${width}`, exact: true }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.screenshot({ path: path.join(output, `mcp-visual-${width}.png`), fullPage: true });
    await page.getByTestId('mcp-open-file').click();
    await reader.waitFor();
    await editor.waitFor();
    await editorReady();
    assert.equal(JSON.parse(await editor.inputValue()).servers[0].name, `可视化编辑 ${width}`);
    await visual.waitFor({ state: 'detached' });
    assert.equal(await page.getByTestId('mcp-settings').count(), 0, 'settings deep link closes visual management and opens JSON');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.screenshot({ path: path.join(output, `mcp-json-${width}.png`), fullPage: true });
    await page.reload({ waitUntil: 'domcontentloaded' }); await reader.waitFor();
    await editor.waitFor();
    assert.equal(JSON.parse(await editor.inputValue()).servers[0].name, `可视化编辑 ${width}`);
    await page.getByTestId('nav-back').click();
    await page.getByRole('navigation', { name: '资料路径' }).getByRole('button', { name: '全部资料', exact: true }).click();
    console.log(`MCP resource UI ${width}px: raw JSON resources, visual Settings edits, secret exclusion, invalid JSON, concurrent draft retention, persistence and Settings deep link passed`);
  }
  assert.deepEqual(errors, []);
  console.log(`Screenshots: ${output}`);
} catch (error) {
  if (errors.length) console.error('Browser errors:', errors);
  if (page) await page.screenshot({ path: path.join(output, 'mcp-failure.png'), fullPage: true }).catch(() => {});
  throw error;
} finally {
  await browser?.close(); await vite?.close(); await api.close(); fs.rmSync(directory, { recursive: true, force: true });
}
