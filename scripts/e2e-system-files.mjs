import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import { chromium } from 'playwright';
import { createServer } from 'vite';

const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'wangke-system-files-ui-'));
const reservation = net.createServer();
await new Promise(resolve => reservation.listen(0, '127.0.0.1', resolve));
const port = reservation.address().port;
await new Promise(resolve => reservation.close(resolve));
const origin = `http://127.0.0.1:${port}`;
Object.assign(process.env, { NODE_ENV: 'test', PUBLIC_ORIGIN: origin, DATA_DIR: directory, FILES_DIR: path.join(directory, 'files'), BOOTSTRAP_SECRET_FILE: path.join(directory, 'config/bootstrap-secret'), CLOUD_WORKER_DISABLED: '1' });
const { buildServer } = await import('../apps/api/src/server.ts');
const api = buildServer({ dbPath: path.join(directory, 'db.sqlite'), fetch: async () => { throw new Error('no model requests expected'); } });
let vite, browser, page;
const errors = [];
const output = process.env.SCREENSHOT_DIR ?? path.join(directory, 'screenshots');
fs.mkdirSync(output, { recursive: true });
try {
  const backend = await api.listen({ host: '127.0.0.1', port: 0 });
  process.env.WANGKE_API_PROXY = backend;
  vite = await createServer({ root: new URL('../apps/web', import.meta.url).pathname, server: { host: '127.0.0.1', port, strictPort: true } });
  await vite.listen();
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ locale: 'zh-CN', serviceWorkers: 'block' });
  const post = async (url, data, headers = {}) => {
    const response = await context.request.post(`${origin}/api/v1${url}`, { headers: { origin, ...headers }, data });
    assert.equal(response.ok(), true, `${url}: ${response.status()} ${await response.text()}`);
    return response;
  };
  assert.equal((await post('/bootstrap/initialize', { adminPassword: 'system-files-ui-password' }, { 'X-Bootstrap-Secret': fs.readFileSync(process.env.BOOTSTRAP_SECRET_FILE, 'utf8').trim() })).status(), 201);
  assert.equal((await post('/auth/password/login', { password: 'system-files-ui-password' })).status(), 200);
  const configuration = await (await context.request.get(`${origin}/api/v1/cloud/config`)).json();
  const configured = await context.request.put(`${origin}/api/v1/cloud/config`, { headers: { origin }, data: { ...configuration, providers: [{ id: 'offline', name: 'Offline', baseUrl: 'https://offline.invalid/v1', protocol: 'openai-chat', apiKey: 'test-only', catalogId: '', serves: ['chat'] }], llmModel: { providerId: 'offline', model: 'test' }, visionModel: { providerId: '', model: '' }, asrModel: { providerId: '', model: '' }, decisionModel: { providerId: '', model: '' } } });
  assert.equal(configured.ok(), true, `configure fixture: ${configured.status()} ${await configured.text()}`);
  await post('/cloud/records', { mutations: [{ id: 'language', table: 'preferences', key: 'uiLanguage', before: null, after: { id: 'uiLanguage', value: 'zh-CN' } }] });
  const memory = await (await post('/bot/memories', { scope: 'owner', scopeId: '', kind: 'preference', content: '# 学习偏好\n\n用简洁中文回答。', source: 'user:management' })).json();
  const resource = `/system/memory/${memory.id}.md`;
  const diaryPath = '/system/memory/2026-10-28.md';
  await post('/system/file', { path: diaryPath, content: '# 2026-10-28\n\n今天复习了线性代数。', expected: '', revision: 0 });
  await post('/system/file', { path: '/system/memory/preferences.md', content: '# 学习笔记\n\n先给例子，再给推导。', expected: '', revision: 0 });
  page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await context.route('https://models.dev/**', route => route.fulfill({ json: {} }));
  let projectListRequests = 0;
  await context.route('**/api/v1/projects', route => {
    projectListRequests++;
    return route.fulfill({ status: 500, json: { error: 'project_list_unavailable' } });
  });
  for (const width of process.env.SKILLS_ONLY ? [] : [1440, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(`${origin}/#/library`);
    const open = item => width < 600 ? item.click() : item.dblclick();
    const systemFolder = page.getByTestId('system-folder');
    await systemFolder.waitFor({ timeout: 60000 });
    await page.waitForFunction(() => document.querySelector('.resource-count')?.textContent === '1 个条目');
    const search = page.getByRole('searchbox', { name: '搜索当前文件夹' });
    await search.fill('SYSTEM');
    await systemFolder.waitFor();
    assert.equal(await page.getByText('没有匹配的文件', { exact: true }).count(), 0);
    await search.fill('missing-folder');
    await systemFolder.waitFor({ state: 'hidden' });
    await page.getByText('没有匹配的文件', { exact: true }).waitFor();
    await search.fill('');
    await systemFolder.waitFor();
    await page.screenshot({ path: path.join(output, `resources-${width}.png`) });
    await open(systemFolder);
    const agentFile = page.getByTestId('agent-instructions-file');
    await agentFile.waitFor();
    const agentCover = agentFile.locator('.finder-document img');
    await agentCover.waitFor();
    await page.waitForFunction(() => {
      const img = document.querySelector('[data-testid="agent-instructions-file"] .finder-document img');
      return img?.complete && img.naturalWidth > 0;
    });
    assert.equal(await agentFile.locator('.finder-file-extension').innerText(), 'MD');
    assert.equal(await agentFile.locator('.finder-document').evaluate(el => getComputedStyle(el).width), width < 600 ? '60px' : '74px', 'AGENTS.md keeps the original document shape on desktop and mobile');
    const memoryFolder = page.getByTestId('memory-folder');
    await memoryFolder.waitFor();
    assert.equal(projectListRequests, 0, 'system folders must not depend on the project directory API');
    assert.equal(await page.getByText('操作失败，请重试。', { exact: true }).count(), 0);
    await page.screenshot({ path: path.join(output, `system-${width}.png`) });
    await open(memoryFolder);
    const file = page.getByTestId('memory-file').filter({ hasText: memory.id });
    await file.waitFor();
    await page.getByTestId('memory-file').filter({ hasText: '2026-10-28.md' }).waitFor();
    await page.getByTestId('memory-file').filter({ hasText: 'preferences.md' }).waitFor();
    assert.equal(projectListRequests, 0, 'memory listing must only load system documents');
    assert.equal(await page.getByRole('navigation', { name: '资料路径' }).getByRole('button', { name: 'memory', exact: true }).isVisible(), true);
    assert.equal(await page.getByTestId('btn-new-folder').isDisabled(), true);
    await page.screenshot({ path: path.join(output, `memory-${width}.png`) });
    await open(file);
    const reader = page.getByTestId('material-reader');
    await reader.waitFor();
    const edit = page.getByTestId('md-edit-toggle');
    await edit.click();
    const editor = page.getByTestId('md-editor').locator('.cm-content');
    const text = `# 学习偏好\n\n资料中修改 ${width}：先举例，再推导。`;
    await editor.fill(text);
    await edit.click();
    await editor.waitFor({ state: 'hidden' });
    assert.match(await reader.innerText(), new RegExp(`资料中修改 ${width}`));
    const rows = await (await context.request.get(`${origin}/api/v1/bot/memories`)).json();
    assert.equal(rows.memories.find(row => row.id === memory.id).content, text);
    await page.reload();
    await reader.waitFor();
    await page.getByText(`资料中修改 ${width}：先举例，再推导。`, { exact: true }).first().waitFor();
    const current = rows.memories.find(row => row.id === memory.id);
    const remoteText = `Bot 同步更新 ${width}`;
    await post('/bot/memories', { id: current.id, revision: current.revision, scope: current.scope, scopeId: current.scope_id, kind: current.kind, content: remoteText, source: current.source });
    await reader.getByText(remoteText, { exact: true }).waitFor({ timeout: 15000 });
    await edit.click();
    const draft = `还没保存的草稿 ${width}`;
    await editor.fill(draft);
    const latest = (await (await context.request.get(`${origin}/api/v1/bot/memories`)).json()).memories.find(row => row.id === memory.id);
    const concurrentText = `其他页面并发修改 ${width}`;
    await post('/bot/memories', { id: latest.id, revision: latest.revision, scope: latest.scope, scopeId: latest.scope_id, kind: latest.kind, content: concurrentText, source: latest.source });
    await edit.click();
    await page.getByTestId('md-save-error').waitFor();
    assert.equal(await editor.innerText(), draft, 'conflicts retain the visible draft');
    assert.equal((await (await context.request.get(`${origin}/api/v1/system/file?path=${resource}`)).json()).content, concurrentText);
    await page.reload();
    await reader.getByText(concurrentText, { exact: true }).waitFor();
    await page.getByTestId('nav-back').click();
    await file.waitFor();
    await page.getByRole('navigation', { name: '资料路径' }).getByRole('button', { name: 'system', exact: true }).click();
    await open(page.getByTestId('agent-instructions-file'));
    await reader.waitFor();
    await edit.click();
    await editor.fill(`# 全局偏好\n\n指令文件编辑 ${width}`);
    await edit.click();
    await editor.waitFor({ state: 'hidden' });
    const instructions = await (await context.request.get(`${origin}/api/v1/system/file?path=/system/AGENTS.md`)).json();
    assert.equal(instructions.content, `# 全局偏好\n\n指令文件编辑 ${width}`);
    await page.goto(`${origin}/#/settings/agent`);
    const settings = page.getByTestId('agent-instructions');
    await settings.waitFor();
    assert.equal(await settings.inputValue(), instructions.content);
    await settings.fill(`设置中即时修改 ${width}`);
    await page.getByTestId('agent-instructions-open-file').click();
    await reader.getByText(`设置中即时修改 ${width}`, { exact: true }).waitFor();
    await page.getByTestId('nav-back').click();
    await agentCover.waitFor();
    const initialAgentCover = await agentCover.getAttribute('src');
    await page.evaluate(async () => {
      const { useSettings } = await import('/src/store/settings.ts');
      useSettings.getState().update({ agentInstructions: '# 新的封面标题\n\n指令变化会更新封面。' });
    });
    await page.waitForFunction(previous => {
      const img = document.querySelector('[data-testid="agent-instructions-file"] .finder-document img');
      return img?.src !== previous && img?.complete && img.naturalWidth > 0;
    }, initialAgentCover);
    // Deep links from memory management and tools work without entering the directory first.
    await page.getByRole('navigation', { name: '资料路径' }).getByRole('button', { name: '全部资料', exact: true }).click();
    await systemFolder.waitFor();
    await page.goto(`${origin}/#/library?file=${resource}`);
    await reader.waitFor();
    assert.match(page.url(), /system%3Amemory%3A/);
    assert.equal(projectListRequests, 0, 'system deep links must not request the project directory either');
    await page.screenshot({ path: path.join(output, `reader-${width}.png`) });
    console.log(`System documents UI ${width}px: navigation, live Bot ↔ Markdown, conflict draft retention, reload, two-way instructions and deep links passed`);
    await page.getByTestId('nav-back').click();
    await file.waitFor();
    await open(page.getByTestId('memory-file').filter({ hasText: '2026-10-28.md' }));
    await reader.getByText('今天复习了线性代数。', { exact: true }).waitFor();
    assert.match(page.url(), /system%3Amemory%3A2026-10-28/);
    const tools = await page.evaluate(async () => {
      const { createResourceExecutor } = await import('/src/harness/resources.ts');
      const execute = createResourceExecutor();
      const path = '/system/memory/browser-notes.md';
      const created = await execute('edit', { path, create: true, content: '浏览器基础工具维护的笔记。' });
      const grep = await execute('grep', { path: '/system/memory', query: '浏览器基础工具' });
      return { created, grep };
    });
    if (width === 1440) assert.match(tools.created, /已创建笔记/);
    assert.match(tools.grep, /browser-notes\.md/);
    await page.getByTestId('nav-back').click();
    await file.waitFor();
    await page.getByRole('navigation', { name: '资料路径' }).getByRole('button', { name: '全部资料', exact: true }).click();
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(`${origin}/#/settings/skills`);
  await page.getByTestId('card-skills').waitFor();
  const builtinRow = page.getByTestId('skill-row').filter({ hasText: '课程讲义' });
  await builtinRow.waitFor();
  await page.getByTestId('btn-skill-new').click();
  await page.getByTestId('skill-name').locator('input').fill('Library Sync Skill');
  await page.getByTestId('skill-desc').locator('input').fill('设置创建的测试技能');
  await page.getByTestId('skill-body').locator('textarea').fill('设置创建的技能正文');
  await page.getByTestId('skill-dialog').locator('input[type=file]').setInputFiles({ name: 'guide.md', mimeType: 'text/markdown', buffer: Buffer.from('# 参考指南\n\n设置添加的参考文件') });
  await page.getByText('references/guide.md', { exact: true }).waitFor();
  await page.getByTestId('skill-save').click();
  await page.getByTestId('skill-dialog').waitFor({ state: 'hidden' });
  const settingsSkill = page.getByTestId('skill-row').filter({ hasText: 'Library Sync Skill' });
  await settingsSkill.waitFor();
  await page.keyboard.press('Escape');
  await page.goto(`${origin}/#/library`);
  await page.getByTestId('system-folder').dblclick();
  await page.getByTestId('system-skill-folder').filter({ has: page.locator('[title="/system/skills"]') }).dblclick();
  await page.getByTestId('system-skill-folder').filter({ hasText: 'course-handout' }).waitFor();
  await page.getByTestId('system-skill-folder').filter({ hasText: 'library-sync-skill-' }).dblclick();
  const skillFile = page.getByTestId('skill-file').filter({ hasText: 'SKILL.md' });
  const skillPath = await skillFile.getAttribute('data-system-file');
  await skillFile.dblclick();
  const skillReader = page.getByTestId('material-reader'), skillEdit = page.getByTestId('md-edit-toggle');
  await skillReader.getByText('设置创建的技能正文', { exact: true }).waitFor();
  await skillEdit.click();
  const skillEditor = page.getByTestId('md-editor').locator('.cm-content');
  await skillEditor.fill('---\nname: Library Sync Skill\ndescription: 资料库更新的描述\n---\n\n资料库更新的正文');
  await skillEdit.click();
  await skillEditor.waitFor({ state: 'hidden' });
  await skillReader.getByText('资料库更新的正文', { exact: true }).waitFor();
  await page.getByTestId('nav-back').click();
  await page.getByTestId('system-skill-folder').filter({ hasText: 'references' }).dblclick();
  await page.getByTestId('skill-file').filter({ hasText: 'guide.md' }).dblclick();
  await skillReader.getByText('设置添加的参考文件', { exact: true }).waitFor();
  await page.goto(`${origin}/#/settings/skills`);
  await settingsSkill.getByText('资料库更新的描述', { exact: true }).waitFor();
  await settingsSkill.getByTestId('skill-edit').click();
  assert.equal(await page.getByTestId('skill-body').locator('textarea').inputValue(), '资料库更新的正文');
  await page.getByTestId('skill-body').locator('textarea').fill('设置再次修改的正文');
  await page.getByTestId('skill-save').click();
  await page.getByTestId('skill-dialog').waitFor({ state: 'hidden' });
  await page.keyboard.press('Escape');
  await page.goto(`${origin}/#/library?file=${skillPath}`);
  await skillReader.getByText('设置再次修改的正文', { exact: true }).waitFor();
  // Builtins have the same editable file source and are not reset by opening Settings.
  await page.goto(`${origin}/#/library?file=/system/skills/course-handout/SKILL.md`);
  await skillReader.waitFor();
  const builtinText = (await (await context.request.get(`${origin}/api/v1/system/file?path=/system/skills/course-handout/SKILL.md`)).json()).content;
  await skillEdit.click();
  await skillEditor.fill(`${builtinText}\n\n用户的内置技能修改`);
  await skillEdit.click();
  await skillEditor.waitFor({ state: 'hidden' });
  await page.goto(`${origin}/#/settings/skills`);
  await builtinRow.getByTestId('skill-edit').click();
  assert.match(await page.getByTestId('skill-body').locator('textarea').inputValue(), /用户的内置技能修改/);
  await page.getByTestId('skill-cancel').click();
  await page.reload();
  await builtinRow.getByTestId('skill-edit').click();
  assert.match(await page.getByTestId('skill-body').locator('textarea').inputValue(), /用户的内置技能修改/);
  console.log('Skill UI: settings create → actual library folders/references → library edit → settings update → builtin edit survives reload passed');
  assert.deepEqual(errors, []);
  console.log(`Screenshots: ${output}`);
} catch (error) {
  if (page && !page.isClosed()) {
    const text = await page.locator('body').innerText().catch(() => 'unavailable');
    fs.writeFileSync(path.join(output, 'failure.txt'), JSON.stringify({ url: page.url(), errors, text }, null, 2));
    await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {});
    console.error(`UI failure at ${page.url()}: ${errors.join('\n')}\n${text.slice(0, 3000)}\nDiagnostics: ${output}`);
  }
  throw error;
} finally {
  await browser?.close();
  await vite?.close();
  await api.close();
  fs.rmSync(directory, { recursive: true, force: true });
}
