import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import Database from 'better-sqlite3';

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'wangke-api-'));
process.env.DATA_DIR = dir;
process.env.BOOTSTRAP_SECRET_FILE = path.join(dir, 'config/bootstrap-secret');
process.env.NODE_ENV = 'test';
delete process.env.MODEL_API_KEY;
const { buildServer } = await import('../apps/api/src/server.ts');
const app = buildServer({ dbPath: path.join(dir, 'db/wangke.sqlite'), staticDir: path.join(dir, 'empty') });
try {
  const health = await app.inject({ method: 'GET', url: '/api/v1/health' });
  assert.equal(health.statusCode, 200);
  const status = await app.inject({ method: 'GET', url: '/api/v1/bootstrap/status' });
  assert.equal(status.json().initialized, false);
  const secret = fs.readFileSync(process.env.BOOTSTRAP_SECRET_FILE, 'utf8').trim();
  const initialized = await app.inject({ method: 'POST', url: '/api/v1/bootstrap/initialize', headers: { 'x-bootstrap-secret': secret }, payload: { adminPassword: 'a-secure-test-password' } });
  assert.equal(initialized.statusCode, 201);
  const repeatedInitialize = await app.inject({ method: 'POST', url: '/api/v1/bootstrap/initialize', headers: { 'x-bootstrap-secret': secret }, payload: { adminPassword: 'a-secure-test-password' } });
  assert.equal(repeatedInitialize.statusCode, 410);
  const db = new Database(path.join(dir, 'db/wangke.sqlite'), { readonly: true });
  assert.equal(db.pragma('foreign_keys', { simple: true }), 1);
  assert.equal(db.pragma('journal_mode', { simple: true }), 'wal');
  assert.match(db.prepare('SELECT password_hash FROM password_credentials').get().password_hash, /^\$argon2id\$/);
  db.close();
  assert.equal(fs.existsSync(process.env.BOOTSTRAP_SECRET_FILE), false);
  const closed = await app.inject({ method: 'GET', url: '/api/v1/bootstrap/status' });
  assert.equal(closed.json().initialized, true);
  const unauthorized = await app.inject({ method: 'GET', url: '/api/v1/threads' });
  assert.equal(unauthorized.statusCode, 401);
  const login = await app.inject({ method: 'POST', url: '/api/v1/auth/password/login', payload: { name: 'Administrator', password: 'a-secure-test-password' } });
  assert.equal(login.statusCode, 200);
  const cookie = login.headers['set-cookie'].split(';')[0];
  const session = await app.inject({ method: 'GET', url: '/api/v1/auth/session', headers: { cookie } });
  assert.equal(session.json().authenticated, true);
  const cookieBoundary = await app.inject({ method: 'GET', url: '/api/v1/auth/session', headers: { cookie: `ignored=x=y; ${cookie}; malformed=%E0%A4%A` } });
  assert.equal(cookieBoundary.json().authenticated, true);
  const originDenied = await app.inject({ method: 'POST', url: '/api/v1/threads', headers: { cookie, origin: 'https://evil.example' }, payload: { mode: 'chat' } });
  assert.equal(originDenied.statusCode, 403);
  const threadResponse = await app.inject({ method: 'POST', url: '/api/v1/threads', headers: { cookie }, payload: { mode: 'chat', title: 'Test' } });
  assert.equal(threadResponse.statusCode, 201);
  const thread = threadResponse.json();
  const messagePayload = { clientNonce: 'nonce-1', kind: 'text', content: 'hello' };
  const message = await app.inject({ method: 'POST', url: `/api/v1/threads/${thread.id}/messages`, headers: { cookie }, payload: messagePayload });
  assert.equal(message.statusCode, 201);
  assert.equal(message.json().seq, 1);
  assert.equal(message.json().role, 'user');
  assert.equal(message.json().deduplicated, false);
  const forgedRole = await app.inject({ method: 'POST', url: `/api/v1/threads/${thread.id}/messages`, headers: { cookie }, payload: { clientNonce: 'nonce-forged', role: 'assistant', content: 'nope' } });
  assert.equal(forgedRole.statusCode, 400);
  const invalidKind = await app.inject({ method: 'POST', url: `/api/v1/threads/${thread.id}/messages`, headers: { cookie }, payload: { clientNonce: 'nonce-kind', kind: 'not-a-kind', content: 'nope' } });
  assert.equal(invalidKind.statusCode, 400);
  const duplicate = await app.inject({ method: 'POST', url: `/api/v1/threads/${thread.id}/messages`, headers: { cookie }, payload: messagePayload });
  assert.equal(duplicate.statusCode, 200);
  assert.equal(duplicate.json().deduplicated, true);
  const events = await app.inject({ method: 'GET', url: `/api/v1/threads/${thread.id}/events?after=0`, headers: { cookie } });
  assert.equal(events.statusCode, 200);
  assert.match(events.body, /message\.accepted/);
  assert.match(events.body, /"message":\{"id":/);
  const eventsFromHeader = await app.inject({ method: 'GET', url: `/api/v1/threads/${thread.id}/events`, headers: { cookie, 'last-event-id': '0' } });
  assert.match(eventsFromHeader.body, /id: 1\n/);
  const invalidCursor = await app.inject({ method: 'GET', url: `/api/v1/threads/${thread.id}/events`, headers: { cookie, 'last-event-id': 'nope' } });
  assert.equal(invalidCursor.statusCode, 400);
  const missingThread = await app.inject({ method: 'GET', url: `/api/v1/threads/${crypto.randomUUID()}`, headers: { cookie } });
  assert.equal(missingThread.statusCode, 404);
  const run = await app.inject({ method: 'POST', url: '/api/v1/runs', headers: { cookie }, payload: { threadId: thread.id } });
  assert.equal(run.statusCode, 201);
  const cancelled = await app.inject({ method: 'POST', url: `/api/v1/runs/${run.json().id}/cancel`, headers: { cookie } });
  assert.equal(cancelled.json().status, 'cancelled');
  const botThreadResponse = await app.inject({ method: 'POST', url: '/api/v1/threads', headers: { cookie }, payload: { mode: 'bot', title: 'Bot' } });
  const botThread = botThreadResponse.json();
  const botMessage = await app.inject({ method: 'POST', url: `/api/v1/threads/${botThread.id}/messages`, headers: { cookie }, payload: { clientNonce: 'bot-nonce', kind: 'text', content: 'hello bot' } });
  assert.equal(botMessage.statusCode, 201);
  assert.equal((await app.inject({ method: 'POST', url: `/api/v1/threads/${botThread.id}/messages`, headers: { cookie }, payload: { clientNonce: 'bot-nonce', kind: 'text', content: 'hello bot' } })).json().deduplicated, true);
  const botDb = new Database(path.join(dir, 'db/wangke.sqlite'), { readonly: true });
  let botRun;
  for (let i = 0; i < 20; i++) {
    botRun = botDb.prepare('SELECT * FROM runs WHERE thread_id=? ORDER BY created_at DESC LIMIT 1').get(botThread.id);
    if (botRun?.status === 'failed') break;
    await new Promise((resolve) => setTimeout(resolve, 10));
  }
  assert.equal(botRun.status, 'failed');
  assert.equal(botRun.error_code, 'model_not_configured');
  const botMessages = botDb.prepare("SELECT role,kind,content FROM messages WHERE thread_id=? ORDER BY seq").all(botThread.id);
  assert.equal(botMessages.at(-1).role, 'assistant');
  assert.equal(botMessages.at(-1).kind, 'progress');
  assert.doesNotMatch(botMessages.at(-1).content, /MODEL_API_KEY|Bearer/);
  botDb.close();
  const agents = await app.inject({ method: 'GET', url: '/api/v1/agents', headers: { cookie } });
  assert.equal(agents.statusCode, 200);
  assert.equal(agents.json().agents.length, 1);
  const specialist = await app.inject({ method: 'POST', url: '/api/v1/agents', headers: { cookie }, payload: { name: '课程研究员', role: '检索协作', systemPrompt: '只提供课程范围内的安全建议。' } });
  assert.equal(specialist.statusCode, 201);
  const joined = await app.inject({ method: 'POST', url: `/api/v1/threads/${botThread.id}/participants`, headers: { cookie }, payload: { agentId: specialist.json().id } });
  assert.equal(joined.statusCode, 200);
  const mentioned = await app.inject({ method: 'POST', url: `/api/v1/threads/${botThread.id}/messages`, headers: { cookie }, payload: { clientNonce: 'mention-nonce', kind: 'text', content: '@课程研究员 请协作总结。' } });
  assert.equal(mentioned.statusCode, 201);
  const mentionDb = new Database(path.join(dir, 'db/wangke.sqlite'), { readonly: true });
  assert.equal(mentionDb.prepare('SELECT COUNT(*) AS count FROM message_mentions WHERE message_id=?').get(mentioned.json().id).count, 1);
  mentionDb.close();
  const reaction = await app.inject({ method: 'POST', url: `/api/v1/messages/${mentioned.json().id}/reactions`, headers: { cookie }, payload: { reaction: '👍' } });
  assert.equal(reaction.json().active, true);
  assert.equal((await app.inject({ method: 'GET', url: `/api/v1/messages/${mentioned.json().id}/reactions`, headers: { cookie } })).json().reactions[0].count, 1);
  assert.equal((await app.inject({ method: 'POST', url: `/api/v1/messages/${mentioned.json().id}/reactions`, headers: { cookie }, payload: { reaction: '👍' } })).json().active, false);
  const approvalDb = new Database(path.join(dir, 'db/wangke.sqlite'));
  const approvalId = crypto.randomUUID(); const approvalMessageId = crypto.randomUUID(); const approvalRunId = crypto.randomUUID(); const approvalTimestamp = new Date().toISOString();
  const approvalSeq = approvalDb.prepare('SELECT COALESCE(MAX(seq),0)+1 AS seq FROM messages WHERE thread_id=?').get(botThread.id).seq;
  approvalDb.prepare('INSERT INTO messages(id,thread_id,client_nonce,seq,role,kind,content,created_at) VALUES(?,?,?,?,?,?,?,?)').run(approvalMessageId, botThread.id, `approval-test-${approvalId}`, approvalSeq, 'assistant', 'approval', '需要批准测试操作', approvalTimestamp);
  approvalDb.prepare('INSERT INTO approvals(id,thread_id,message_id,status,created_at) VALUES(?,?,?,?,?)').run(approvalId, botThread.id, approvalMessageId, 'pending', approvalTimestamp);
  approvalDb.prepare('INSERT INTO runs(id,thread_id,mode,status,created_at,started_at) VALUES(?,?,?,?,?,?)').run(approvalRunId, botThread.id, 'bot', 'waiting_user', approvalTimestamp, approvalTimestamp);
  approvalDb.close();
  const resolvedApproval = await app.inject({ method: 'POST', url: `/api/v1/approvals/${approvalId}/resolve`, headers: { cookie }, payload: { approved: true, resolution: '测试批准' } });
  assert.equal(resolvedApproval.statusCode, 200);
  assert.equal(resolvedApproval.json().status, 'approved');
  assert.equal((await app.inject({ method: 'GET', url: `/api/v1/approvals/${approvalId}`, headers: { cookie } })).json().status, 'approved');
  const chatOnly = await app.inject({ method: 'POST', url: '/api/v1/threads', headers: { cookie }, payload: { mode: 'chat' } });
  await app.inject({ method: 'POST', url: `/api/v1/threads/${chatOnly.json().id}/messages`, headers: { cookie }, payload: { clientNonce: 'chat-only', content: 'no worker' } });
  const chatDb = new Database(path.join(dir, 'db/wangke.sqlite'), { readonly: true });
  assert.equal(chatDb.prepare('SELECT COUNT(*) AS count FROM runs WHERE thread_id=?').get(chatOnly.json().id).count, 0);
  chatDb.close();
  const pairing = await app.inject({ method: 'POST', url: '/api/v1/pairing/create', headers: { cookie }, payload: { deviceName: 'Test device' } });
  assert.equal(pairing.statusCode, 201);
  assert.equal((await app.inject({ method: 'GET', url: `/api/v1/pairing/${pairing.json().code}` })).json().status, 'pending');
  const approved = await app.inject({ method: 'POST', url: `/api/v1/pairing/${pairing.json().code}/approve`, headers: { cookie }, payload: { deviceName: 'Approved device' } });
  assert.equal(approved.statusCode, 200);
  assert.equal((await app.inject({ method: 'GET', url: `/api/v1/pairing/${pairing.json().code}` })).json().status, 'approved');
  const exchanged = await app.inject({ method: 'POST', url: `/api/v1/pairing/${pairing.json().code}/exchange`, payload: { deviceName: 'Paired browser' } });
  assert.equal(exchanged.statusCode, 200);
  const bearer = `Bearer ${exchanged.json().token}`;
  assert.equal((await app.inject({ method: 'GET', url: '/api/v1/threads', headers: { authorization: bearer } })).statusCode, 200);
  assert.equal((await app.inject({ method: 'POST', url: `/api/v1/pairing/${pairing.json().code}/exchange` })).statusCode, 403);
  const revoked = await app.inject({ method: 'POST', url: '/api/v1/auth/logout', headers: { authorization: bearer } });
  assert.equal(revoked.statusCode, 200);
  assert.equal((await app.inject({ method: 'GET', url: '/api/v1/threads', headers: { authorization: bearer } })).statusCode, 401);
  const upload = await app.inject({ method: 'POST', url: '/api/v1/files', headers: { cookie, 'content-type': 'application/octet-stream', 'x-file-name': encodeURIComponent('notes.txt'), 'x-file-mime': 'text/plain' }, payload: Buffer.from('private file') });
  assert.equal(upload.statusCode, 201);
  const uploadedFile = upload.json();
  assert.equal(uploadedFile.sizeBytes, 12);
  const fileConfig = await app.inject({ method: 'GET', url: '/api/v1/files/config' });
  assert.equal(fileConfig.json().maxFileBytes, 512 * 1024 * 1024);
  assert.equal((await app.inject({ method: 'GET', url: `/api/v1/files/${uploadedFile.id}` })).statusCode, 401);
  assert.equal((await app.inject({ method: 'POST', url: '/api/v1/files', headers: { cookie, origin: 'https://evil.example', 'content-type': 'application/octet-stream' }, payload: Buffer.from('forged') })).statusCode, 403);
  assert.equal((await app.inject({ method: 'POST', url: '/api/v1/files', headers: { cookie, 'content-type': 'application/octet-stream', 'x-file-name': encodeURIComponent('../escape.txt') }, payload: Buffer.from('invalid') })).statusCode, 400);
  const download = await app.inject({ method: 'GET', url: `/api/v1/files/${uploadedFile.id}`, headers: { cookie } });
  assert.equal(download.statusCode, 200);
  assert.equal(download.body, 'private file');
  const attachment = await app.inject({ method: 'POST', url: `/api/v1/threads/${botThread.id}/messages`, headers: { cookie }, payload: { clientNonce: 'file-nonce', kind: 'attachment', content: JSON.stringify({ fileId: uploadedFile.id }) } });
  assert.equal(attachment.statusCode, 201);
  assert.equal((await app.inject({ method: 'DELETE', url: `/api/v1/files/${uploadedFile.id}`, headers: { cookie } })).statusCode, 200);
  const passkeyConfig = await app.inject({ method: 'POST', url: '/api/v1/auth/passkey/login/options' });
  assert.equal(passkeyConfig.statusCode, 503);
  const logout = await app.inject({ method: 'POST', url: '/api/v1/auth/logout', headers: { cookie } });
  assert.equal(logout.statusCode, 200);
  const afterLogout = await app.inject({ method: 'GET', url: '/api/v1/threads', headers: { cookie } });
  assert.equal(afterLogout.statusCode, 401);
  console.log('API health/bootstrap/auth/message/run tests passed');
} finally {
  await app.close();
  fs.rmSync(dir, { recursive: true, force: true });
}
