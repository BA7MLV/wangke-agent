import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { Readable } from 'node:stream';
import { DatabaseStore } from '../apps/api/src/storage/database.ts';
import { ProjectRepository } from '../apps/api/src/projects/repository.ts';
import { ResourceFiles } from '../apps/api/src/projects/resources.ts';
import { BotApplicationService } from '../apps/api/src/agent/service.ts';
import { CloudConfiguration } from '../apps/api/src/cloud/config.ts';
import { StudyTools } from '../apps/api/src/agent/study.ts';
import { receiveFile } from '../apps/api/src/cloud/files.ts';
import { UsageLedger } from '../apps/api/src/agent/budget.ts';
import { ModelClient } from '../apps/api/src/agent/model-client.ts';
import { botRequest } from '../apps/api/src/agent/model.ts';
import { botPauseMessage, botProgressText } from '../packages/contracts/src/cloud.ts';

const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'bot-resources-'));
const filename = path.join(directory, 'db.sqlite'), files = path.join(directory, 'files');
fs.mkdirSync(files);
let store = new DatabaseStore(filename);
try {
  const owner = crypto.randomUUID(), other = crypto.randomUUID(), at = new Date().toISOString();
  for (const id of [owner, other]) store.db.prepare('INSERT INTO users VALUES(?,?,?)').run(id, id, at);
  let projects = new ProjectRepository(store, path.join(directory, 'projects'));
  let resources = new ResourceFiles(projects, files);
  const service = new BotApplicationService(store, { enqueue() {} }, projects);
  const thread = service.create(owner, 'bot', 'Files');
  const foreign = service.create(other, 'bot', 'Private');
  const config = new CloudConfiguration(store, path.join(directory, 'config'));
  const upload = (who, name, text = name) => receiveFile(store, files, who, Readable.from([Buffer.from(text)]), name, 'text/plain', 10000);
  const photo = await upload(owner, 'photo.png');
  service.send(owner, thread.id, { clientNonce: 'photo', kind: 'attachment', content: JSON.stringify({ fileId: photo.id }) });
  const legacy = await upload(owner, 'photo.png', 'different bytes');
  service.send(owner, thread.id, { clientNonce: 'gateway', content: `Attachment fileId=${legacy.id}, name=photo.png, mime=image/png. Use study_file to read/understand it.` });
  const privateFile = await upload(other, 'private.txt');
  service.append(foreign.id, 'assistant', 'attachment', JSON.stringify({ fileId: privateFile.id }));
  // Even a forged historical file reference cannot import another owner's bytes.
  service.append(thread.id, 'assistant', 'attachment', JSON.stringify({ fileId: privateFile.id }));
  await upload(owner, 'unused.txt');
  const tools = new StudyTools(store, config, files);
  const ctx = { owner, thread: thread.id, run: '', step: 'export-once', signal: new AbortController().signal, checkActive() {}, append: (kind, text) => service.append(thread.id, 'assistant', kind, text) };
  const exported = await tools.plugins.get('study_export').execute({ name: 'notes.md', content: '# Generated notes' }, ctx);
  let listing = resources.list(owner);
  assert.deepEqual(listing.entries.map(e => e.name).sort(), ['notes.md', 'photo (2).png', 'photo.png']);
  const root = listing.rootId;
  assert.equal(resources.list(other).entries[0].name, 'private.txt');
  assert.ok(listing.entries.find(e => e.name === 'notes.md').courseId, 'export is a usable learning resource');
  assert.equal(projects.files.read(root, 'notes.md').text, '# Generated notes');
  await tools.plugins.get('study_send_file').execute({ fileId: exported.fileId }, ctx);
  assert.equal(resources.list(owner).entries.length, 3, 're-sending the same file is not another library item');
  projects.files.move(root, 'photo.png', root, 'renamed.png', listing.entries.find(e => e.name === 'photo.png').revision);
  listing = resources.list(owner);
  assert.ok(listing.entries.some(e => e.name === 'renamed.png'));
  assert.ok(!listing.entries.some(e => e.name === 'photo.png'));
  projects.files.remove(root, 'renamed.png', listing.entries.find(e => e.name === 'renamed.png').revision);
  assert.equal(resources.list(owner).entries.length, 2, 'deleted attachments are not resurrected');

  // Crash recovery after installation but before marking a receipt done.
  const pending = await upload(owner, 'recover.txt', 'complete bytes');
  service.append(thread.id, 'assistant', 'attachment', JSON.stringify({ fileId: pending.id }));
  store.db.prepare("INSERT INTO resource_attachments VALUES(?,?,?,?,'pending')").run(owner, pending.id, root, 'recover.txt');
  projects.files.copy(root, 'recover.txt', path.join(files, `${pending.id}.bin`));
  assert.equal(resources.list(owner).entries.filter(e => e.name.startsWith('recover')).length, 1);
  const collision = await upload(owner, 'collision.txt', 'Bot output');
  service.append(thread.id, 'assistant', 'attachment', JSON.stringify({ fileId: collision.id }));
  store.db.prepare("INSERT INTO resource_attachments VALUES(?,?,?,?,'pending')").run(owner, collision.id, root, 'collision.txt');
  projects.files.write(root, 'collision.txt', 'user edit', null);
  resources.list(owner);
  assert.equal(projects.files.read(root, 'collision.txt').text, 'user edit');
  assert.equal(projects.files.read(root, 'collision (2).txt').text, 'Bot output');
  const scopedProject = projects.create(owner, 'Scoped'), scopedThread = crypto.randomUUID();
  store.db.prepare("INSERT INTO threads(id,owner_id,mode,title,created_at,updated_at,project_id) VALUES(?,?,'bot','Scoped',?,?,?)").run(scopedThread, owner, at, at, scopedProject.id);
  const scopedExport = await upload(owner, 'scoped-export.csv', 'a,b');
  service.append(scopedThread, 'assistant', 'attachment', JSON.stringify({ fileId: scopedExport.id }));
  assert.ok(resources.list(owner).entries.some(e => e.name === 'scoped-export.csv'), 'blob exports from project conversations are visible too');

  const batchFiles = await Promise.all(['batch-a.txt', 'batch-b.txt'].map(name => upload(owner, name)));
  const batch = { attachments: batchFiles.map(file => ({ fileId: file.id })), caption: 'Read both' };
  const beforeBatch = store.db.prepare('SELECT COUNT(*) n FROM runs WHERE thread_id=?').get(thread.id).n;
  service.send(owner, thread.id, { clientNonce: 'batch', kind: 'attachment', content: JSON.stringify(batch) });
  assert.equal(store.db.prepare('SELECT COUNT(*) n FROM runs WHERE thread_id=?').get(thread.id).n, beforeBatch + 1, 'one run for the entire composed message');
  assert.ok(resources.list(owner).entries.some(e => e.name === 'batch-a.txt'));
  assert.ok(resources.list(owner).entries.some(e => e.name === 'batch-b.txt'), 'every batched file reaches the resource library');
  assert.throws(() => service.send(owner, thread.id, { clientNonce: 'foreign-batch', kind: 'attachment', content: JSON.stringify({ attachments: [{ fileId: photo.id }, { fileId: privateFile.id }] }) }), /invalid_message/);
  assert.equal(store.db.prepare("SELECT 1 FROM messages WHERE client_nonce='foreign-batch'").get(), undefined, 'mixed-owner batches are rejected atomically');

  const pref = (id, value) => store.db.prepare("INSERT INTO cloud_records(owner_id,table_name,record_key,value) VALUES(?,'preferences',?,?) ON CONFLICT(owner_id,table_name,record_key) DO UPDATE SET value=excluded.value").run(owner, JSON.stringify(id), JSON.stringify({ id, value }));
  const provider = { id: 'main', name: 'Main', baseUrl: 'https://model.invalid/v1', protocol: 'openai-chat', apiKey: 'test', serves: ['chat'], catalogId: '' };
  config.save(owner, { ...config.get(owner, true), providers: [provider], llmModel: { providerId: 'main', model: 'custom' }, botBudget: { runTokens: 250000, dayTokens: 1000000, activeMs: 900000, contextTokens: 32000, prices: [] } });
  pref('contextWindow', 1050000);
  const ledger = new UsageLedger(store, config);
  assert.equal(ledger.limits(owner).contextTokens, 1050000);
  assert.equal(ledger.limits(owner).runTokens, undefined);
  assert.equal(ledger.limits(owner).dayTokens, undefined);
  assert.equal(ledger.limits(owner).activeMs, undefined);
  pref('savedModels', [{ providerId: 'other', model: 'custom', contextWindow: 100 }, { providerId: 'main', model: 'custom', contextWindow: 500000, maxOutputTokens: 12000 }]);
  assert.deepEqual(ledger.model(owner), { model: 'custom', contextTokens: 500000, outputTokens: 12000 });
  const run = store.db.prepare('SELECT id FROM runs WHERE thread_id=? LIMIT 1').get(thread.id).id;
  store.db.prepare("UPDATE runs SET status='running',budget_json=? WHERE id=?").run(JSON.stringify({ runTokens: 250000, dayTokens: 1000000, activeMs: 900000, contextTokens: 32000 }), run);
  assert.equal(ledger.limits(owner, run).contextTokens, 500000, 'old paused run snapshots follow the main model too');
  const wire = botRequest(provider, 'custom', [{ role: 'user', content: 'A'.repeat(50000) }], [], ledger.model(owner).outputTokens);
  let called = 0;
  const model = new ModelClient(ledger, async (_url, init) => { called++; assert.equal(JSON.parse(init.body).max_tokens, 12000); return Response.json({ usage: { prompt_tokens: 20000, completion_tokens: 1 } }); });
  await model.request(`${provider.baseUrl}/${wire.path}`, { body: JSON.stringify(wire.body) }, { owner, run, purpose: 'bot', provider: 'main', model: 'custom' }, 1);
  assert.equal(called, 1, 'request beyond the former 32k cap reaches the selected model');
  pref('savedModels', [{ providerId: 'main', model: 'custom', contextWindow: 20000, maxOutputTokens: 2000 }]);
  await assert.rejects(model.request(`${provider.baseUrl}/${wire.path}`, { body: JSON.stringify(wire.body) }, { owner, run, purpose: 'bot', provider: 'main', model: 'custom' }, 1), /context_capacity_exceeded/);
  assert.equal(called, 1, 'smaller explicit model windows still enforced');
  pref('savedModels', [{ providerId: 'main', model: 'custom', contextWindow: 50 }]);
  assert.equal(ledger.limits(owner).contextTokens, 50, 'valid main-model input must not turn into invalid_bot_budget');
  assert.equal(botProgressText('预算已暂停任务：context_capacity_exceeded。请调整预算后显式继续。'), botPauseMessage('context_capacity_exceeded'));

  store.close(); store = new DatabaseStore(filename);
  projects = new ProjectRepository(store, path.join(directory, 'projects')); resources = new ResourceFiles(projects, files);
  assert.ok(!resources.list(owner).entries.some(e => e.name === 'photo.png' || e.name === 'renamed.png'), 'receipts survive restart');
  console.log('Bot resources/model settings: Web + legacy IM attachments, exports, deduplication, owner isolation, move/delete/restart, crash recovery, shared model window/output, legacy defaults passed');
} finally { store.close(); fs.rmSync(directory, { recursive: true, force: true }); }
