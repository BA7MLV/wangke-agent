import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import 'fake-indexeddb/auto';
import Dexie from 'dexie';
import { installCloudCache, markCloudApply } from '../apps/web/src/cloud/cache.ts';
import { DatabaseStore } from '../apps/api/src/storage/database.ts';
import { CloudRecords, CloudConflict } from '../apps/api/src/cloud/records.ts';
import { CloudConfiguration } from '../apps/api/src/cloud/config.ts';
import { BotRunner } from '../apps/api/src/agent/runner.ts';
import { receiveFile, byteRange } from '../apps/api/src/cloud/files.ts';
import { Readable } from 'node:stream';
import { botRequest, botCalls } from '../apps/api/src/agent/model.ts';
import { CloudTaskRunner } from '../apps/api/src/cloud/tasks.ts';

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'wangke-cloud-'));
const store = new DatabaseStore(path.join(dir, 'db.sqlite'));
const owner = crypto.randomUUID(), other = crypto.randomUUID();
for (const id of [owner, other]) store.db.prepare('INSERT INTO users(id,name,created_at) VALUES(?,?,?)').run(id, id, new Date().toISOString());
const records = new CloudRecords(store);
const mutation = (table, key, before, after) => ({ id: crypto.randomUUID(), table, key, before, after });
let runner;
const db = new Dexie(`test-cloud-${crypto.randomUUID()}`);
db.version(1).stores({ videos: 'id', chats: '++id', _cloudOutbox: '++sequence,transaction' });
installCloudCache(db);
try {
  const original = { id: 'a', name: 'lecture', lastPosition: 0 };
  const create = mutation('videos', 'a', null, original);
  records.apply(owner, [create]); records.apply(owner, [create]);
  assert.equal(records.list(owner, 0).length, 1);
  assert.equal(records.get(other, 'videos', 'a'), null);
  records.apply(owner, [mutation('videos', 'a', original, { ...original, lastPosition: 10 })]);
  records.apply(owner, [mutation('videos', 'a', original, { ...original, name: 'renamed' })]);
  assert.deepEqual(records.get(owner, 'videos', 'a'), { ...original, name: 'renamed', lastPosition: 10 });
  assert.throws(() => records.apply(owner, [mutation('videos', 'a', original, { ...original, name: 'conflicting' })]), CloudConflict);
  const beforeDelete = records.get(owner, 'videos', 'a');
  records.apply(owner, [mutation('videos', 'a', beforeDelete, null)]);
  assert.throws(() => records.apply(owner, [mutation('videos', 'a', beforeDelete, { ...beforeDelete, name: 'resurrection' })]), CloudConflict);
  assert.equal(records.list(owner, 0)[0].value, null);
  const revision = records.list(owner, 0)[0].revision;
  assert.throws(() => records.apply(owner, [mutation('videos', 'a', null, original)]), CloudConflict);
  records.apply(owner, [{ ...mutation('videos', 'a', null, original), baseRevision: revision }]);
  const day = { date: '2026-10-22', seconds: 5, updatedAt: 1 };
  records.apply(owner, [mutation('studyDays', day.date, null, day)]);
  records.apply(owner, [mutation('studyDays', day.date, null, day)]);
  records.apply(owner, [mutation('studyDays', day.date, day, { ...day, seconds: 8 })]);
  assert.equal(records.get(owner, 'studyDays', day.date).seconds, 13);
  records.apply(owner, [mutation('preferences', 'theme', null, { id: 'theme', value: 'light' })]);
  records.apply(owner, [mutation('preferences', 'theme', null, { id: 'theme', value: 'dark' })]);
  assert.equal(records.get(owner, 'preferences', 'theme').value, 'dark');
  assert.throws(() => records.apply(owner, [mutation('videos', 'rollback', null, { id: 'rollback' }), mutation('badTable', 'x', null, { id: 'x' })]));
  assert.equal(records.get(owner, 'videos', 'rollback'), null);

  await db.open();
  const id = await db.table('chats').add({ content: 'hello' });
  assert.ok(id > 1000000 && Number.isSafeInteger(id));
  let box = await db.table('_cloudOutbox').toArray();
  assert.equal(box[0].after.id, id);
  await assert.rejects(db.transaction('rw', db.table('videos'), async () => { await db.table('videos').put({ id: 'rollback' }); throw new Error('rollback'); }));
  assert.equal(await db.table('_cloudOutbox').count(), 1);
  await db.transaction('rw', db.table('videos'), async () => { markCloudApply(); await db.table('videos').put({ id: 'server' }); });
  assert.equal(await db.table('_cloudOutbox').count(), 1);
  await db.table('chats').update(id, { content: 'updated' });
  await db.table('chats').clear();
  box = await db.table('_cloudOutbox').toArray();
  assert.equal(box[1].before.content, 'hello');
  assert.equal(box.at(-1).key, id); assert.equal(box.at(-1).after, null);

  const config = new CloudConfiguration(store, path.join(dir, 'config'));
  const value = { ...config.get(owner), providers: [{ id: 'test', name: 'Test', baseUrl: 'https://model.example/v1', apiKey: 'super-secret', protocol: 'openai-chat', catalogId: '', serves: ['chat'] }], llmModel: { providerId: 'test', model: 'test-model' } };
  config.save(owner, value);
  assert.equal(config.get(owner).providers[0].apiKey, undefined);
  assert.equal(config.get(owner).providers[0].configured, true);
  config.save(owner, config.get(owner));
  assert.equal(config.get(owner, true).providers[0].apiKey, 'super-secret');
  assert.ok(!store.db.prepare('SELECT value FROM cloud_config').get().value.includes('super-secret'));
  assert.equal(new CloudConfiguration(store, path.join(dir, 'config')).get(owner, true).providers[0].apiKey, 'super-secret');
  const files = path.join(dir, 'files'); fs.mkdirSync(files);
  const file = await receiveFile(store, files, owner, Readable.from([Buffer.from('abc'), Buffer.from('def')]), 'test.txt', 'text/plain', 6);
  assert.equal(file.sizeBytes, 6);
  assert.equal(file.sha256, crypto.createHash('sha256').update('abcdef').digest('hex'));
  await assert.rejects(receiveFile(store, files, owner, Readable.from([Buffer.alloc(7)]), 'test', 'text/plain', 6));
  assert.equal(fs.readdirSync(files).length, 1);
  assert.deepEqual(byteRange('bytes=-2', 6), { start: 4, end: 5 });
  assert.equal(byteRange('bytes=7-', 6), false);
  const cached1 = await receiveFile(store, files, owner, Readable.from(['identical']), 'cache-blob', 'text/plain', 20);
  const cached2 = await receiveFile(store, files, owner, Readable.from(['identical']), 'cache-blob', 'text/plain', 20);
  assert.equal(cached1.id, cached2.id, 'identical blob references must remain stable across devices');
  const envelope = [{ role: 'assistant', content: null, tool_calls: [{ id: 'c1', type: 'function', function: { name: 'shell', arguments: '{"command":"pwd"}' } }] }, { role: 'tool', tool_call_id: 'c1', content: '/workspace' }];
  const anthropic = botRequest({ protocol: 'anthropic-messages', apiKey: 'key' }, 'claude', envelope, []);
  assert.equal(anthropic.body.messages[1].content[0].tool_use_id, 'c1');
  assert.equal(anthropic.headers['x-api-key'], 'key');
  const responses = botRequest({ protocol: 'openai-responses' }, 'model', envelope, []);
  assert.equal(responses.body.input[1].call_id, 'c1');
  assert.equal(botCalls('openai-responses', { output: [{ type: 'function_call', name: 'shell', arguments: '{}' }] })[0].function.name, 'shell');
  for (const status of ['running', 'waiting_user']) {
    store.db.prepare('INSERT INTO cloud_tasks(id,owner_id,nonce,kind,resource,input,status,created_at,updated_at) VALUES(?,?,?,?,?,?,?,?,?)')
      .run(status, owner, status, 'chat', status, '{}', status, '2026-10-22', '2026-10-22');
    store.db.prepare('INSERT INTO cloud_permissions(id,owner_id,task_id,capability,arguments,created_at) VALUES(?,?,?,?,?,?)')
      .run(status, owner, status, 'write', '{}', '2026-10-22');
  }
  const cloudRunner = new CloudTaskRunner(store);
  cloudRunner.start('http://127.0.0.1:1');
  assert.equal(store.db.prepare("SELECT COUNT(*) AS n FROM cloud_tasks WHERE status='interrupted'").get().n, 2);
  assert.equal(store.db.prepare("SELECT COUNT(*) AS n FROM cloud_permissions WHERE status='expired'").get().n, 2);
  await cloudRunner.close();

  const thread = crypto.randomUUID(), run = crypto.randomUUID(), timestamp = new Date().toISOString();
  store.db.prepare('INSERT INTO threads(id,owner_id,mode,created_at,updated_at) VALUES(?,?,?,?,?)').run(thread, owner, 'bot', timestamp, timestamp);
  const agent = crypto.randomUUID();
  store.db.prepare('INSERT INTO agent_profiles(id,owner_id,name,role,system_prompt,created_at,updated_at) VALUES(?,?,?,?,?,?,?)').run(agent, owner, 'Trusted', 'assistant', '', timestamp, timestamp);
  store.db.prepare('INSERT INTO thread_participants(thread_id,agent_id,joined_at) VALUES(?,?,?)').run(thread, agent, timestamp);
  config.save(owner, { ...config.get(owner), trustedAgentIds: [agent] });
  assert.equal(config.policy(owner, thread).shell, 'allow');
  assert.equal(config.policy(owner, thread).network, 'deny');
  config.save(owner, { ...config.get(owner), policy: { ...config.get(owner).policy, shell: 'deny' } });
  assert.equal(config.policy(owner, thread).shell, 'deny');
  config.save(owner, { ...config.get(owner), trustedAgentIds: [], policy: { ...config.get(owner).policy, shell: 'ask' } });
  assert.equal(config.policy(owner, thread).shell, 'ask', 'revoking trust restores one-shot approval');
  store.db.prepare('INSERT INTO runs(id,thread_id,mode,status,created_at) VALUES(?,?,?,?,?)').run(run, thread, 'bot', 'queued', timestamp);
  let calls = 0, executed = 0;
  const response = (name, args) => new Response(JSON.stringify({ choices: [{ message: { tool_calls: [{ function: { name, arguments: JSON.stringify(args) } }] } }] }));
  runner = new BotRunner(store, { configuration: config, fetch: async () => ++calls === 1 ? response('shell', { command: 'echo approved' }) : response('send_message', { kind: 'text', text: 'done' }), sandbox: async req => { executed++; assert.equal(req.command, 'echo approved'); assert.equal(req.network, false); return { stdout: 'approved', stderr: '', exitCode: 0 }; } });
  const until = async fn => { for (let i = 0; i < 300; i++) { if (fn()) return; await new Promise(r => setTimeout(r, 10)); } throw new Error('Timeout'); };
  runner.start();
  await until(() => store.db.prepare('SELECT status FROM runs WHERE id=?').get(run).status === 'waiting_user');
  assert.equal(executed, 0);
  await runner.close();
  store.db.prepare("UPDATE approvals SET status='approved' WHERE run_id=?").run(run);
  store.db.prepare("UPDATE runs SET status='queued' WHERE id=?").run(run);
  runner = new BotRunner(store, { configuration: config, fetch: async () => response('send_message', { kind: 'text', text: 'done' }), sandbox: async req => { executed++; assert.equal(req.command, 'echo approved'); return { stdout: 'approved', stderr: '', exitCode: 0 }; } });
  runner.start(); await until(() => store.db.prepare('SELECT status FROM runs WHERE id=?').get(run).status === 'completed');
  assert.equal(executed, 1);
  console.log('Cloud records, conflicts, atomic outbox, credentials, streaming files and durable one-shot approvals passed');
} finally {
  await runner?.close(); await db.delete(); store.close(); fs.rmSync(dir, { recursive: true, force: true });
}
