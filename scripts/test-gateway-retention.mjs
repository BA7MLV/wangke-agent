import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DatabaseStore } from '../apps/api/src/storage/database.ts';
import { CloudConfiguration } from '../apps/api/src/cloud/config.ts';
import { BotApplicationService } from '../apps/api/src/agent/service.ts';
import { GatewayCore } from '../apps/api/src/gateway/core.ts';
import { cleanupGateway } from '../apps/api/src/gateway/retention.ts';
import { appendAudit } from '../apps/api/src/storage/audit.ts';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'gateway-retention-'));
const store = new DatabaseStore(path.join(root, 'db.sqlite'));
const cfg = new CloudConfiguration(store, path.join(root, 'config'));
const owner = 'retention-owner', at = new Date().toISOString();
store.db.prepare('INSERT INTO users VALUES(?,?,?)').run(owner, owner, at);
store.db.prepare('INSERT INTO agent_profiles(id,owner_id,name,role,system_prompt,created_at,updated_at) VALUES(?,?,?,?,?,?,?)').run('agent', owner, 'Fake', '', '', at, at);
const bot = new BotApplicationService(store, { enqueue() {}, cancel() {} });
const plugin = () => ({ manifest: { id: 'test-channel', version: 1, name: 'Fake', configFields: [{ key: 'token', label: 'Token', secret: true, required: false, write: 'replace-or-preserve' }], loginSteps: [{ action: 'login', label: 'Login', fields: ['code'] }], loginConfigFields: ['token'], loginPublicFields: ['status'], capabilities: { direct: true, groups: false, files: false, images: false, proactive: 'yes', deduplicationWindowMs: 0 } }, validate() {}, async login() { return { status: 'ok', token: 'PRIVATE', unknownSecret: 'NEVER-RETURN' }; }, async start() {}, async stop() {}, async send() { return 'sent'; } });
const gateway = new GatewayCore(store, cfg, bot, { 'test-channel': plugin }, root);
try {
  const { id } = await gateway.save(owner, { channel: 'test-channel', agentId: 'agent', enabled: false, config: { token: 'OLD' } });
  await gateway.save(owner, { id, channel: 'test-channel', agentId: 'agent', enabled: false, config: { token: '' } });
  assert.equal(gateway.config(gateway.account(owner, id)).token, 'OLD');
  assert.deepEqual(await gateway.login(owner, id, { action: 'login', code: 'test' }), { status: 'ok' });
  assert.equal(gateway.config(gateway.account(owner, id)).token, 'PRIVATE');
  assert.ok(!JSON.stringify(gateway.list(owner)).includes('PRIVATE'));
  await assert.rejects(gateway.login(owner, id, { action: 'unknown' }), /invalid_channel_login_action/);
  const thread = bot.create(owner, 'bot', 'Retention');
  store.db.prepare('INSERT INTO gateway_bindings(id,account_id,tenant,peer,chat,topic,thread_id) VALUES(?,?,?,?,?,?,?)').run('binding', id, '', 'me', 'chat', '', thread.id);
  process.env.GATEWAY_PENDING_LIMIT = '2';
  gateway.enqueue('binding', 'one', { text: 'one' }); gateway.enqueue('binding', 'two', { text: 'two' });
  assert.throws(() => gateway.enqueue('binding', 'three', { text: 'three' }), /capacity/);
  gateway.enqueue('binding', 'one', { text: 'one' });
  store.db.prepare('UPDATE gateway_accounts SET enabled=1 WHERE id=?').run(id);
  const envelope = messageId => ({ messageId, tenant: '', peer: 'me', chat: 'chat', topic: '', direct: true, human: true, text: 'hello' });
  gateway.receive(id, [envelope('one'), envelope('two')], 'cursor-1');
  assert.throws(() => gateway.receive(id, [envelope('three')], 'cursor-2'), /capacity/);
  assert.equal(gateway.account(owner, id).cursor, 'cursor-1');
  const old = Date.now() - 120 * 86400000;
  store.db.prepare("UPDATE gateway_inbox SET status='done',received_at=?").run(old);
  store.db.prepare("UPDATE gateway_outbox SET status='sent',created_at=? WHERE payload LIKE '%one%'").run(old);
  store.db.prepare("UPDATE gateway_outbox SET status='uncertain',created_at=? WHERE payload LIKE '%two%'").run(old);
  cleanupGateway(store);
  assert.equal(store.db.prepare("SELECT envelope FROM gateway_inbox LIMIT 1").get().envelope, '');
  assert.equal(store.db.prepare("SELECT payload FROM gateway_outbox WHERE status='sent'").get().payload, '{}');
  assert.ok(store.db.prepare("SELECT payload FROM gateway_outbox WHERE status='uncertain'").get().payload.includes('two'));
  gateway.receive(id, [envelope('one')], 'cursor-3');
  assert.equal(store.db.prepare('SELECT COUNT(*) AS n FROM gateway_inbox').get().n, 2, 'body cleanup never removes replay identity');
  assert.equal(gateway.account(owner, id).cursor, 'cursor-3');
  gateway.enqueue('binding', 'expired', { text: 'expired' });
  store.db.prepare("UPDATE gateway_outbox SET created_at=? WHERE status='pending'").run(old);
  cleanupGateway(store);
  assert.equal(store.db.prepare("SELECT error FROM gateway_outbox WHERE status='failed'").get().error, 'pending_expired');
  process.env.BOT_AUDIT_LIMIT = '1000';
  for (let i = 0; i < 1100; i++) appendAudit(store, owner, 'test', { i });
  assert.equal(store.db.prepare('SELECT COUNT(*) AS n FROM cloud_audit WHERE owner_id=?').get(owner).n, 1000);
  console.log('Gateway retention passed: fake plugin contract/login masking, blank-secret preserve, capacities/cursor rollback, permanent replay identity, terminal body cleanup, uncertain preservation, expiration and bounded audit.');
} finally { delete process.env.GATEWAY_PENDING_LIMIT; delete process.env.BOT_AUDIT_LIMIT; await gateway.close(); store.close(); fs.rmSync(root, { recursive: true, force: true }); }
