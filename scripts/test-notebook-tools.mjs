import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { DatabaseStore } from '../apps/api/src/storage/database.ts';
import { CloudConfiguration } from '../apps/api/src/cloud/config.ts';
import { CloudRecords } from '../apps/api/src/cloud/records.ts';
import { SystemMaterials } from '../apps/api/src/storage/system-materials.ts';
import { BotMemory } from '../apps/api/src/agent/memory.ts';
import { StudyTools } from '../apps/api/src/agent/study.ts';
import { BotApplicationService } from '../apps/api/src/agent/service.ts';
import { BotRunner } from '../apps/api/src/agent/runner.ts';
import { ToolRegistry } from '../apps/api/src/agent/tools/registry.ts';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'wangke-notebook-'));
let store = new DatabaseStore(path.join(root, 'db.sqlite'));
let runner;
try {
  const owner = 'notebook-owner', other = 'notebook-other', at = new Date().toISOString();
  for (const id of [owner, other]) store.db.prepare('INSERT INTO users VALUES(?,?,?)').run(id, id, at);
  const config = new CloudConfiguration(store, path.join(root, 'config'));
  config.save(owner, { ...config.get(owner, true), providers: [{ id: 'offline', name: 'Offline', baseUrl: 'https://offline.invalid/v1', protocol: 'openai-chat', apiKey: 'test', serves: ['chat'] }], llmModel: { providerId: 'offline', model: 'test' }, policy: { ...config.get(owner).policy, read: 'allow', write: 'allow', maxSteps: 30 } });
  const service = new BotApplicationService(store, { enqueue() {}, cancel() {} });
  const thread = service.create(owner, 'bot', 'Notebook');
  const message = service.send(owner, thread.id, { clientNonce: 'notebook', content: '记下今天的学习过程，并整理成笔记。' });
  const run = store.db.prepare('SELECT id FROM runs WHERE trigger_message_id=?').get(message.id).id;
  const tools = new StudyTools(store, config, path.join(root, 'files'));
  const registry = new ToolRegistry();
  for (const definition of tools.definitions()) registry.register(definition, ['read', 'grep'].includes(definition.function.name) ? 'read' : 'uncertain');
  for (const name of ['read', 'grep', 'edit']) assert.ok(registry.definitions().some(d => d.function.name === name));
  let sequence = 0;
  const context = (account = owner) => ({ owner: account, thread: thread.id, run, step: `notebook-${++sequence}`, signal: new AbortController().signal, checkActive() {}, append() {} });
  const invoke = (name, args, account) => {
    assert.equal(registry.validate(name, args).ok, true);
    return tools.plugins.get(name).execute(args, context(account));
  };
  const documents = new SystemMaterials(store), memories = new BotMemory(store);
  const physical = (resource, account = owner) => path.join(store.systemFiles.root, crypto.createHash('sha256').update(account).digest('hex'), resource.slice(1));
  const diary = '/system/memory/2026-10-28.md', note = '/system/memory/preferences.md';
  assert.equal((await invoke('read', { path: '/system/memory' })).files.length, 0);
  const created = await invoke('edit', { path: diary, revision: 0, create: true, content: '今天完成线性代数复习；下一步验证例题。' });
  assert.equal(created.kind, 'diary');
  assert.equal(created.revision, 1);
  assert.match(fs.readFileSync(physical(diary), 'utf8'), /^# 2026-10-28\n\n## \d{4}-\d{2}-\d{2}T/);
  await invoke('edit', { path: diary, revision: 1, append: '已验证例题；行列式计算还有不确定性。' });
  let document = documents.read(owner, diary);
  assert.equal(document.revision, 2);
  assert.equal((document.content.match(/^## /gm) ?? []).length, 2);
  assert.match(document.content, /下一步验证例题/);
  const hit = await invoke('grep', { path: '/system/memory', query: '行列式' });
  assert.equal(hit.hits[0].path, diary);
  assert.ok(hit.hits[0].line > 0);
  await invoke('edit', { path: diary, revision: 2, edits: [{ old_string: '还有不确定性', new_string: '已逐步核实' }] });
  await assert.rejects(invoke('edit', { path: diary, revision: 1, append: '过期编辑' }), /conflict/);
  await assert.rejects(invoke('edit', { path: diary, revision: 0, create: true, content: '不能覆盖' }), /conflict/);
  await assert.rejects(invoke('edit', { path: '/system/memory/2026-02-30.md', revision: 0, create: true, content: '无效日期' }), /invalid_diary_date/);
  await invoke('edit', { path: note, revision: 0, create: true, content: '先给例子，再讲结论。' });
  assert.equal(documents.read(owner, note).kind, 'note');
  const literalPath = '/system/memory/literal-edits.md';
  await invoke('edit', { path: literalPath, revision: 0, create: true, content: 'same same\n[.*]\nabcde' });
  await assert.rejects(invoke('edit', { path: literalPath, revision: 1, edits: [{ old_string: 'same', new_string: 'one' }] }), /edit_ambiguous/);
  await assert.rejects(invoke('edit', { path: literalPath, revision: 1, edits: [{ old_string: 'abc', new_string: 'x' }, { old_string: 'cde', new_string: 'y' }] }), /edit_overlap/);
  await assert.rejects(invoke('edit', { path: literalPath, revision: 1, append: 'x', edits: [{ old_string: '[.*]', new_string: 'literal' }] }), /invalid_edit_mode/);
  assert.equal(documents.read(owner, literalPath).revision, 1, 'rejected edits leave content and revision unchanged');
  await invoke('edit', { path: literalPath, revision: 1, edits: [{ old_string: 'same', new_string: 'one', replace_all: true }, { old_string: '[.*]', new_string: 'literal' }] });
  assert.equal(documents.read(owner, literalPath).content, 'one one\nliteral\nabcde');
  const literalRow = memories.list(owner).find(row => row.path === literalPath);
  memories.remove(owner, literalRow.id, literalRow.revision);
  assert.equal(memories.context(owner, thread.id).length, 0, 'diaries and notes are retrieved, not injected as preferences');
  assert.equal((await invoke('grep', { path: '/system/memory', query: '结论' }, other)).hits.length, 0);
  await assert.rejects(invoke('read', { path: '/etc/passwd' }), /invalid_system_path/);
  await assert.rejects(invoke('edit', { path: '/system/AGENTS.md', revision: 0, edits: [{ old_string: '不存在', new_string: 'x' }] }), /edit_not_found/);
  assert.equal(store.db.prepare('SELECT source FROM bot_memories WHERE kind=? AND owner_id=?').get('diary', owner).source, `message:${message.id}`);
  console.log('Notebook tools: named notes, dated/timestamped diaries, read/grep/exact edit/append, CAS, provenance, path and account isolation passed');

  // Files are authoritative, including external creates, edits and deletions.
  document = documents.read(owner, note);
  fs.writeFileSync(physical(note), '磁盘修改是真正的笔记正文。');
  assert.equal(documents.read(owner, note).content, '磁盘修改是真正的笔记正文。');
  assert.throws(() => documents.save(owner, note, '旧编辑器', document.content, document.revision), /conflict/);
  fs.writeFileSync(physical('/system/memory/research.md'), '# 实验记录\n证据 A');
  assert.ok(documents.list(owner, '/system/memory').files.some(file => file.name === 'research.md'));
  const record = memories.list(owner).find(row => row.path === note);
  fs.unlinkSync(physical(note));
  assert.throws(() => documents.read(owner, note), /not_found/);
  assert.equal(memories.get(owner, record.id).status, 'deleted');
  memories.restore(owner, record.id, 1, record.revision + 1);
  assert.equal(fs.readFileSync(physical(note), 'utf8'), '先给例子，再讲结论。');
  documents.read(owner, '/system/AGENTS.md');
  fs.writeFileSync(physical('/system/AGENTS.md'), '请使用简洁中文。');
  const records = new CloudRecords(store);
  records.list(owner, 0);
  assert.equal(records.get(owner, 'preferences', 'agentInstructions').value, '请使用简洁中文。');
  assert.equal(documents.read(owner, '/system/AGENTS.md').content, '请使用简洁中文。');
  console.log('File authority: external note/instruction edits, discovery, deletion tombstones and explicit version restore passed');

  assert.throws(() => store.transaction(() => {
    documents.save(owner, '/system/memory/rollback.md', '不能落盘', '', 0);
    throw new Error('rollback');
  }), /rollback/);
  assert.equal(fs.existsSync(physical('/system/memory/rollback.md')), false);
  assert.equal(documents.list(owner, '/system/memory').files.some(file => file.name === 'rollback.md'), false);
  store.db.transaction(() => documents.save(owner, '/system/memory/replay.md', '待提交到文件', '', 0))();
  assert.equal(fs.existsSync(physical('/system/memory/replay.md')), false);
  store.close(); store = new DatabaseStore(path.join(root, 'db.sqlite'));
  let recovered = new SystemMaterials(store);
  assert.equal(recovered.read(owner, '/system/memory/replay.md').content, '待提交到文件');
  store.db.transaction(() => recovered.save(owner, '/system/memory/race.md', '待写入的旧内容', '', 0))();
  fs.writeFileSync(physical('/system/memory/race.md'), '外部更新优先');
  assert.throws(() => recovered.read(owner, '/system/memory/race.md'), /system_file_changed/);
  assert.equal(recovered.read(owner, '/system/memory/race.md').content, '外部更新优先');
  console.log('Notebook durability: outer transaction rollback, crash replay and no clobber of newer external files passed');

  // Exercise real Bot dispatch, then approval resume with a concurrent disk edit.
  const runtimeConfig = new CloudConfiguration(store, path.join(root, 'config'));
  const runtimeTools = new StudyTools(store, runtimeConfig, path.join(root, 'files'));
  let turn = 0;
  const response = (name, args) => Response.json({ choices: [{ message: { tool_calls: [{ function: { name, arguments: JSON.stringify(args) } }] } }], usage: { prompt_tokens: 10, completion_tokens: 10 } });
  runner = new BotRunner(store, { configuration: runtimeConfig, study: runtimeTools, fetch: async (_url, init) => {
    const body = JSON.parse(init.body);
    assert.ok(body.tools.some(tool => tool.function.name === 'edit'));
    if (++turn === 1) return response('read', { path: diary });
    if (turn === 2) return response('grep', { path: '/system/memory', query: '线性代数' });
    if (turn === 3) return response('edit', { path: diary, revision: 3, append: 'Bot 工具实际记录。' });
    return response('send_message', { kind: 'text', text: '笔记已保存。' });
  } });
  const until = async check => { for (let i = 0; i < 500; i++) { if (check()) return; await new Promise(resolve => setTimeout(resolve, 10)); } throw new Error('runtime timeout'); };
  const state = () => store.db.prepare('SELECT status,error_code FROM runs WHERE id=?').get(run);
  runner.start(); await until(() => ['completed', 'failed', 'paused'].includes(state().status));
  assert.equal(state().status, 'completed', JSON.stringify(state()));
  await runner.close(); runner = undefined;
  assert.match(recovered.read(owner, diary).content, /Bot 工具实际记录/);
  assert.equal(store.db.prepare('SELECT COUNT(*) n FROM bot_memory_jobs WHERE enabled=1').get().n, 0, 'no automatic journaling is enabled');

  runtimeConfig.save(owner, { ...runtimeConfig.get(owner, true), policy: { ...runtimeConfig.get(owner).policy, write: 'ask' } });
  const approvalService = new BotApplicationService(store, { enqueue() {}, cancel() {} });
  const requested = approvalService.send(owner, thread.id, { clientNonce: 'approval', content: '继续写日记。' });
  const approvalRun = store.db.prepare('SELECT id FROM runs WHERE trigger_message_id=?').get(requested.id).id;
  const before = recovered.read(owner, diary);
  turn = 0;
  runner = new BotRunner(store, { configuration: runtimeConfig, study: runtimeTools, fetch: async () => ++turn === 1 ? response('edit', { path: diary, revision: before.revision, append: '不得覆盖并发修改' }) : response('send_message', { kind: 'text', text: '文件已变化，请重新读取。' }) });
  runner.start();
  await until(() => store.db.prepare('SELECT status FROM runs WHERE id=?').get(approvalRun).status === 'waiting_user');
  fs.writeFileSync(physical(diary), `${before.content}\n\n用户在审批期间修改。`);
  store.db.prepare("UPDATE approvals SET status='approved' WHERE run_id=?").run(approvalRun);
  store.db.prepare("UPDATE runs SET status='queued' WHERE id=?").run(approvalRun);
  runner.enqueue();
  await until(() => store.db.prepare('SELECT status FROM runs WHERE id=?').get(approvalRun).status === 'completed');
  assert.match(fs.readFileSync(physical(diary), 'utf8'), /用户在审批期间修改/);
  assert.doesNotMatch(fs.readFileSync(physical(diary), 'utf8'), /不得覆盖并发修改/);
  assert.match(store.db.prepare("SELECT result FROM run_steps WHERE run_id=? AND tool='edit'").get(approvalRun).result, /system_revision_conflict/);
  console.log('Bot notebook dispatch: basic tools, on-demand retrieval, exact approval resume/CAS and no automatic diary scheduling passed');
} finally {
  await runner?.close();
  store.close();
  fs.rmSync(root, { recursive: true, force: true });
}
