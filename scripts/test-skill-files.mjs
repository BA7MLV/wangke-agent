import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { DatabaseStore } from '../apps/api/src/storage/database.ts';
import { SystemMaterials } from '../apps/api/src/storage/system-materials.ts';
import { CloudRecords } from '../apps/api/src/cloud/records.ts';
import { BotSkills } from '../apps/api/src/agent/skills.ts';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'skill-files-'));
const filename = path.join(root, 'db.sqlite'), files = path.join(root, 'system-files');
let store = new DatabaseStore(filename, files);
const owner = 'skill-owner', other = 'other-owner', at = new Date().toISOString();
try {
  for (const id of [owner, other]) store.db.prepare('INSERT INTO users(id,name,created_at) VALUES(?,?,?)').run(id, id, at);
  store.db.prepare("INSERT INTO threads(id,owner_id,mode,created_at,updated_at,skill_ids) VALUES('thread',?,'bot',?,?,'[73]')").run(owner, at, at);
  const legacy = { id: 73, name: '已有技能', description: '设置里的旧技能', body: '原来的正文', enabled: 0, builtin: 0, updatedAt: 1, mcpRequired: ['Explicit MCP'] };
  const ref = { id: 74, skillId: 73, path: 'references/中文指南.md', body: '原来的参考文件' };
  const seed = (table, row) => store.db.prepare('INSERT INTO cloud_records(owner_id,table_name,record_key,value) VALUES(?,?,?,?)').run(owner, table, JSON.stringify(row.id), JSON.stringify(row));
  seed('skills', legacy); seed('skillRefs', ref);
  let materials = new SystemMaterials(store), records = new CloudRecords(store);
  const mutate = (table, before, after, id = before?.id ?? after.id) => records.apply(owner, [{ id: crypto.randomUUID(), table, key: id, before, after }]);
  const listing = materials.list(owner, '/system/skills');
  assert.equal(listing.directories.length, 12, 'all eleven bundled skills plus the existing settings skill');
  const binding = store.db.prepare('SELECT * FROM system_skill_bindings WHERE owner_id=? AND skill_id=73').get(owner);
  const packageRoot = path.join(store.systemSkills.directory(owner), binding.slug);
  const resource = `/system/skills/${binding.slug}/SKILL.md`;
  assert.match(materials.read(owner, resource).content, /原来的正文/);
  assert.equal(fs.readFileSync(path.join(packageRoot, ref.path), 'utf8'), ref.body);
  assert.equal(materials.read(owner, resource).enabled, false);
  assert.equal(store.systemSkills.list(owner).find(s => s.slug === binding.slug).id, 73, 'session IDs survive migration');
  assert.equal(new BotSkills(store).catalog(owner, 'thread').length, 0, 'disabled skills stay disabled');
  assert.deepEqual(records.get(owner, 'skillRefs', 74), ref, 'reference IDs survive migration');
  assert.equal(store.db.prepare('SELECT COUNT(*) AS n FROM mcp_servers').get().n, 0, 'requires-mcp never creates or grants MCP');
  assert.ok(materials.read(owner, '/system/skills/course-handout/references/writing.md').content.length > 100);
  assert.equal(materials.list(other, '/system/skills').directories.length, 11, 'owner isolation');
  console.log('Skill migration: existing settings, bundled packages, references, disabled state, stable IDs and owner isolation passed');

  let current = records.get(owner, 'skills', 73);
  mutate('skills', current, { ...current, enabled: 1 });
  assert.equal(materials.read(owner, resource).enabled, true);
  assert.deepEqual(new BotSkills(store).load(owner, 'thread', 73).missingMcp, ['Explicit MCP']);
  current = records.get(owner, 'skills', 73);
  mutate('skills', current, { ...current, body: '从设置修改正文', mcpRequired: undefined });
  assert.match(fs.readFileSync(path.join(packageRoot, 'SKILL.md'), 'utf8'), /从设置修改正文/);
  assert.equal(new BotSkills(store).load(owner, 'thread', 73).body, '从设置修改正文');
  mutate('skillRefs', ref, { ...ref, body: '从设置修改参考文件' });
  assert.equal(fs.readFileSync(path.join(packageRoot, ref.path), 'utf8'), '从设置修改参考文件');
  const oldSettings = records.get(owner, 'skills', 73);
  let document = materials.read(owner, resource);
  materials.save(owner, resource, document.content.replace('从设置修改正文', '从资料库修改正文').replace('\n---\n\n', '\nversion: 2.0\nlicense: MIT\n---\n\n'), document.content, document.revision);
  assert.equal(records.get(owner, 'skills', 73).body, '从资料库修改正文');
  assert.throws(() => mutate('skills', oldSettings, { ...oldSettings, body: '过期的设置草稿' }), /sync_conflict/);
  current = records.get(owner, 'skills', 73);
  mutate('skills', current, { ...current, description: '新描述' });
  assert.match(materials.read(owner, resource).content, /version: 2\.0\nlicense: MIT/);
  fs.writeFileSync(path.join(packageRoot, ref.path), 'Shell 修改参考文件');
  assert.equal(records.get(owner, 'skillRefs', 74).body, 'Shell 修改参考文件');
  fs.writeFileSync(path.join(packageRoot, 'references/extra.json'), '{"shell":true}');
  const cursor = Math.max(...records.list(owner, 0).map(r => r.revision));
  assert.ok([...store.skillRecords.snapshot(owner).refs.values()].some(r => r.skillId === 73 && r.path === 'references/extra.json'));
  assert.deepEqual(records.list(owner, cursor), [], 'unchanged scans do not churn cloud revisions');
  console.log('Skill synchronization: settings ↔ real files, Shell references, format preservation, CAS and stable cursors passed');

  // A rolled-back cloud batch must never partially mutate the package.
  current = records.get(owner, 'skills', 73);
  const beforeText = fs.readFileSync(path.join(packageRoot, 'SKILL.md'), 'utf8');
  assert.throws(() => store.transaction(() => { mutate('skills', current, { ...current, body: 'rollback' }); throw new Error('rollback'); }), /rollback/);
  assert.equal(fs.readFileSync(path.join(packageRoot, 'SKILL.md'), 'utf8'), beforeText);
  assert.equal(records.get(owner, 'skills', 73).body, current.body);
  assert.throws(() => mutate('skillRefs', null, { id: 75, skillId: 73, path: 'references/../../outside.md', body: 'escape' }), /invalid_skill_reference/);
  assert.equal(records.get(owner, 'skillRefs', 75), null);
  const builtin = materials.read(owner, '/system/skills/course-handout/SKILL.md');
  materials.save(owner, builtin.path, builtin.content.replace(/\s*$/, '\n\n用户保留的内置修改\n'), builtin.content, builtin.revision);
  store.close(); store = new DatabaseStore(filename, files);
  materials = new SystemMaterials(store); records = new CloudRecords(store);
  assert.equal(materials.list(owner, '/system/skills').directories.length, 12);
  assert.match(materials.read(owner, builtin.path).content, /用户保留的内置修改/);
  assert.equal(records.get(owner, 'skills', 73).body, current.body);
  console.log('Skill durability: transaction rollback, path rejection, idempotent restart and builtin edit preservation passed');

  const shellRoot = path.join(store.systemSkills.directory(owner), 'shell-installed');
  fs.mkdirSync(shellRoot);
  fs.writeFileSync(path.join(shellRoot, 'SKILL.md'), '---\nname: Shell Skill\ndescription: installed with Shell\n---\n\nLive package');
  records.list(owner, 0);
  const shell = [...store.skillRecords.snapshot(owner).skills.values()].find(s => s.name === 'Shell Skill');
  assert.ok(shell, 'Shell installs are projected into settings');
  fs.rmSync(shellRoot, { recursive: true });
  assert.equal(records.get(owner, 'skills', shell.id), null, 'deleted files do not resurrect from the projection');
  current = records.get(owner, 'skills', 73);
  mutate('skills', current, null);
  assert.equal(fs.existsSync(path.join(packageRoot, 'SKILL.md')), false);
  assert.equal(materials.list(owner, '/system/skills').directories.includes(`/system/skills/${binding.slug}`), false);
  assert.equal(records.get(owner, 'skills', 73), null);
  assert.equal(records.get(owner, 'skillRefs', 74), null);
  console.log('Skill lifecycle: Shell discovery, settings deletion and deletion tombstones passed');

  const upgradeOwner = 'already-installed';
  store.db.prepare('INSERT INTO users(id,name,created_at) VALUES(?,?,?)').run(upgradeOwner, upgradeOwner, at);
  const installed = path.join(store.systemSkills.directory(upgradeOwner), 'course-handout');
  fs.mkdirSync(installed);
  const customized = '---\nname: 课程讲义\ndescription: Existing package\n---\n\nAlready customized on disk';
  fs.writeFileSync(path.join(installed, 'SKILL.md'), customized);
  store.db.prepare("INSERT INTO cloud_records(owner_id,table_name,record_key,value) VALUES(?,'skills','81',?)").run(upgradeOwner, JSON.stringify({ id: 81, name: '课程讲义', description: 'Old DB', body: 'Old bundled body', enabled: 1, builtin: 1, updatedAt: 0 }));
  assert.equal(materials.list(upgradeOwner, '/system/skills').directories.length, 11, 'an existing builtin folder is adopted rather than duplicated');
  assert.equal(fs.readFileSync(path.join(installed, 'SKILL.md'), 'utf8'), customized);
  assert.equal(records.get(upgradeOwner, 'skills', 81).body, 'Already customized on disk');
  console.log('Skill upgrade: existing physical builtin takes precedence over the old settings copy passed');
} finally { store.close(); fs.rmSync(root, { recursive: true, force: true }); }
