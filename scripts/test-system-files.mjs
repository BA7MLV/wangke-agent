import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'wangke-system-files-'));
Object.assign(process.env, { NODE_ENV: 'test', DATA_DIR: directory, FILES_DIR: path.join(directory, 'files'), BOOTSTRAP_SECRET_FILE: path.join(directory, 'config/bootstrap-secret'), CLOUD_WORKER_DISABLED: '1' });
const { buildServer } = await import('../apps/api/src/server.ts');
const { DatabaseStore } = await import('../apps/api/src/storage/database.ts');
const { BotMemory } = await import('../apps/api/src/agent/memory.ts');
const { BotRunner } = await import('../apps/api/src/agent/runner.ts');
const { CloudRecords } = await import('../apps/api/src/cloud/records.ts');
const { SystemMaterials } = await import('../apps/api/src/storage/system-materials.ts');
const { workerTokens, workerTokenHash } = await import('../apps/api/src/cloud/workerAuth.ts');
const { systemSaveArguments } = await import('../packages/contracts/src/system.ts');
const dbPath = path.join(directory, 'db.sqlite');
const filesRoot = path.join(process.env.FILES_DIR, 'system-files');
let app = buildServer({ dbPath });
let store;
try {
  const post = (url, payload, headers = {}) => app.inject({ method: 'POST', url: `/api/v1${url}`, headers, payload });
  assert.equal((await post('/bootstrap/initialize', { adminPassword: 'system-files-test-password' }, { 'x-bootstrap-secret': fs.readFileSync(process.env.BOOTSTRAP_SECRET_FILE, 'utf8').trim() })).statusCode, 201);
  const login = await post('/auth/password/login', { password: 'system-files-test-password' });
  const cookie = login.headers['set-cookie'].split(';')[0];
  const headers = { cookie };
  const get = url => app.inject({ method: 'GET', url: `/api/v1${url}`, headers });
  const read = async file => {
    const response = await get(`/system/file?path=${encodeURIComponent(file)}`);
    assert.equal(response.statusCode, 200, response.body);
    return response.json();
  };
  const save = (file, content) => post('/system/file', { path: file.path, content, expected: file.content, revision: file.revision }, headers);
  const owner = login.json().user.id;
  const physical = file => path.join(filesRoot, crypto.createHash('sha256').update(owner).digest('hex'), file.slice(1));
  const agents = '/system/AGENTS.md';
  assert.equal((await app.inject({ method: 'GET', url: '/api/v1/system/files?path=/system' })).statusCode, 401);
  assert.deepEqual((await get('/system/files?path=/system')).json().directories, ['/system/memory']);
  const initial = await read(agents);
  assert.equal(initial.content, '');
  assert.equal(fs.readFileSync(physical(agents), 'utf8'), '');
  assert.ok(fs.statSync(physical('/system/memory')).isDirectory());
  assert.equal((await save(initial, '# 偏好\n先给结论。')).statusCode, 200);
  const preference = (await get('/cloud/record?table=preferences&key=%22agentInstructions%22')).json().value;
  assert.equal(preference.value, '# 偏好\n先给结论。');
  assert.equal(fs.readFileSync(physical(agents), 'utf8'), preference.value);
  assert.equal((await save(initial, '过期草稿')).statusCode, 409);
  assert.equal((await post('/system/file', { ...initial, path: agents, expected: '', content: '恶意跨站' }, { ...headers, origin: 'https://evil.invalid' })).statusCode, 403);
  const sync = await post('/cloud/records', { mutations: [{ id: 'settings-edit', table: 'preferences', key: 'agentInstructions', before: preference, after: { ...preference, value: '设置页更新的同一份指令' } }] }, headers);
  assert.equal(sync.statusCode, 200, sync.body);
  assert.equal((await read(agents)).content, '设置页更新的同一份指令');
  assert.equal(fs.readFileSync(physical(agents), 'utf8'), '设置页更新的同一份指令');
  assert.equal((await post('/cloud/records', { mutations: [{ id: 'stale-settings-edit', table: 'preferences', key: 'agentInstructions', before: preference, after: { ...preference, value: '过期的设置页' } }] }, headers)).statusCode, 409);
  console.log('System instructions: real file, settings sync, CAS, auth and origin protection passed');

  const created = await post('/bot/memories', { scope: 'owner', scopeId: '', kind: 'preference', content: '# 学习偏好\n用简洁中文回答。', source: 'user:management' }, headers);
  assert.equal(created.statusCode, 200, created.body);
  const memory = created.json(), resource = `/system/memory/${memory.id}.md`;
  assert.equal(fs.readFileSync(physical(resource), 'utf8'), memory.content);
  let file = await read(resource);
  const list = (await get('/system/files?path=/system/memory')).json();
  assert.equal(list.files[0].path, resource);
  assert.equal(list.files[0].scope, 'owner');
  assert.equal((await save(file, '# 学习偏好\n先举例，再推导。')).statusCode, 200);
  const updated = (await get('/bot/memories')).json().memories.find(row => row.id === memory.id);
  assert.equal(updated.content, '# 学习偏好\n先举例，再推导。');
  assert.equal(updated.revision, 2);
  assert.equal(updated.source, memory.source);
  assert.equal((await save(file, '过期的资料编辑器')).statusCode, 409);
  assert.equal((await post('/bot/memories', { ...updated, scopeId: updated.scope_id, content: 'Bot 更新的记忆' }, headers)).statusCode, 200);
  assert.equal((await read(resource)).content, 'Bot 更新的记忆');
  assert.equal(fs.readFileSync(physical(resource), 'utf8'), 'Bot 更新的记忆');
  assert.equal((await post(`/bot/memories/${memory.id}/delete`, { revision: 3 }, headers)).statusCode, 200);
  assert.equal(fs.existsSync(physical(resource)), false);
  assert.equal((await get(`/system/file?path=${resource}`)).statusCode, 404);
  assert.equal((await get('/system/files?path=/system/memory')).json().files.length, 0);
  assert.equal((await post(`/bot/memories/${memory.id}/restore`, { revision: 1, expected: 4 }, headers)).statusCode, 200);
  assert.equal((await read(resource)).content, memory.content);
  assert.equal(fs.readFileSync(physical(resource), 'utf8'), memory.content);
  console.log('Memory files: Bot ↔ Markdown edits, shared revisions, deletion and historical restore passed');

  store = new DatabaseStore(dbPath, filesRoot);
  const records = new CloudRecords(store), memories = new BotMemory(store);
  const workerToken = crypto.randomUUID(), taskId = crypto.randomUUID(), at = new Date().toISOString();
  store.db.prepare("INSERT INTO cloud_tasks(id,owner_id,nonce,kind,resource,input,status,created_at,updated_at,worker_id,lease_expires_at) VALUES(?,?,?,'qa','system-test','{}','running',?,?,?,?)").run(taskId, owner, taskId, at, at, workerTokenHash(workerToken), new Date(Date.now() + 60000).toISOString());
  workerTokens.set(workerToken, { id: owner, taskId });
  const workerHeaders = { authorization: `Bearer ${workerToken}` };
  assert.equal((await app.inject({ method: 'GET', url: `/api/v1/system/file?path=${resource}`, headers: workerHeaders })).statusCode, 200);
  file = await read(resource);
  const workerSave = { path: resource, content: file.content, expected: file.content, revision: file.revision };
  assert.equal((await post('/system/file', workerSave, workerHeaders)).statusCode, 403);
  const permit = crypto.randomUUID();
  store.db.prepare("INSERT INTO cloud_permissions(id,owner_id,task_id,capability,arguments,created_at,status) VALUES(?,?,?,'write',?,?,'consumed')").run(permit, owner, taskId, JSON.stringify(systemSaveArguments(resource, file.content, file.content, file.revision)), at);
  assert.equal((await post('/system/file', { ...workerSave, content: 'not the approved operation', permissionId: permit }, workerHeaders)).statusCode, 403);
  assert.equal((await post('/system/file', { ...workerSave, permissionId: permit }, workerHeaders)).statusCode, 200);
  assert.equal((await post('/system/file', { ...workerSave, permissionId: permit }, workerHeaders)).statusCode, 403);
  for (const expired of ['2000-01-01T00:00:00.000Z', null, 'invalid-date']) {
    store.db.prepare('UPDATE cloud_tasks SET lease_expires_at=? WHERE id=?').run(expired, taskId);
    assert.equal((await post('/system/file', workerSave, workerHeaders)).statusCode, 409);
  }
  workerTokens.delete(workerToken);
  console.log('System file worker: bearer reads, exact one-shot write approvals, replay and expired-lease rejection passed');
  const course = { id: 'course', name: 'course' };
  records.apply(owner, [{ id: 'course-create', table: 'videos', key: 'course', before: null, after: course }]);
  const fact = memories.save(owner, { scope: 'course', scopeId: 'course', kind: 'course_fact', content: '事实', source: 'record:videos:"course"' });
  const factPath = `/system/memory/${fact.id}.md`;
  records.apply(owner, [{ id: 'course-edit', table: 'videos', key: 'course', before: course, after: { ...course, name: 'changed' } }]);
  const stale = await read(factPath);
  assert.equal(stale.status, 'stale');
  assert.equal((await save(stale, '不能隐式更新来源版本')).statusCode, 400);
  assert.equal(memories.get(owner, fact.id).revision, 1);
  const thread = crypto.randomUUID();
  store.db.prepare("INSERT INTO threads(id,owner_id,mode,title,created_at,updated_at) VALUES(?,?,'bot','System files',?,?)").run(thread, owner, at, at);
  const prompt = new BotRunner(store).initialContext({ thread_id: thread, trigger_message_id: null });
  assert.match(prompt[0].content, /never bypass/);
  assert.match(prompt[1].content, /\/system\/AGENTS\.md/);
  assert.match(prompt[1].content, /设置页更新的同一份指令/);
  assert.deepEqual(memories.context(owner, thread).map(row => row.content), [memory.content]);
  console.log('Bot context: shared AGENTS.md and memory content, unchanged safety contracts and scope boundaries passed');
  const other = 'other-owner';
  store.db.prepare('INSERT INTO users VALUES(?,?,?)').run(other, 'Other', new Date().toISOString());
  assert.throws(() => new SystemMaterials(store).read(other, resource), /memory_not_found/);
  for (const bad of ['/system/../AGENTS.md', '/system/memory/../../secret.md', '/system/memory/%2e%2e%2fsecret.md', '/etc/passwd', '/system/unknown.md']) {
    assert.equal((await get(`/system/file?path=${encodeURIComponent(bad)}`)).statusCode, 400);
  }
  const outside = path.join(directory, 'outside.md');
  fs.writeFileSync(outside, 'not a system file');
  fs.unlinkSync(physical(resource)); fs.symlinkSync(outside, physical(resource));
  assert.equal((await get(`/system/file?path=${resource}`)).statusCode, 400);
  assert.equal(fs.readFileSync(outside, 'utf8'), 'not a system file');
  fs.unlinkSync(physical(resource));
  fs.writeFileSync(physical(resource), '直接在笔记本文件里修改');
  assert.equal((await read(resource)).content, '直接在笔记本文件里修改', 'disk content is authoritative');
  assert.equal(memories.get(owner, memory.id).content, '直接在笔记本文件里修改');
  fs.unlinkSync(physical(resource));
  assert.equal((await get(`/system/file?path=${resource}`)).statusCode, 404, 'a removed file is not recreated from the DB');
  const tombstone = memories.get(owner, memory.id);
  assert.equal(tombstone.status, 'deleted');
  memories.restore(owner, memory.id, 1, tombstone.revision);
  assert.equal((await read(resource)).content, memory.content, 'historical recovery is explicit');
  assert.equal(store.db.prepare("SELECT COUNT(*) n FROM cloud_records WHERE table_name='videos' AND record_key LIKE '%system%'").get().n, 0);
  assert.ok(store.db.prepare('SELECT COUNT(*) n FROM bot_memory_versions WHERE memory_id=?').get(memory.id).n >= 5);
  // Simulate pre-upgrade rows whose files have never been materialized.
  const legacyId = crypto.randomUUID();
  store.db.prepare('INSERT INTO bot_memories SELECT ?,owner_id,scope,scope_id,kind,?,source,source_revision,1,status,origin,created_at,updated_at FROM bot_memories WHERE id=?').run(legacyId, '旧版数据库里的记忆', memory.id);
  store.close(); store = undefined;
  await app.close();
  app = buildServer({ dbPath });
  await app.ready();
  assert.equal(fs.readFileSync(physical(`/system/memory/${legacyId}.md`), 'utf8'), '旧版数据库里的记忆');
  assert.equal((await read(resource)).content, memory.content);
  console.log('System storage: file authority, external edits/deletion, explicit recovery, source freshness, isolation and legacy migration passed');
} finally {
  store?.close();
  await app.close();
  fs.rmSync(directory, { recursive: true, force: true });
}
